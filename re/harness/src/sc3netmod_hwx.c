/* sc3netmod_hwx.c - the HWX block of sc3netmod.dll (task hwx, highway program 2026-10-18): a cloverleaf at a straight
 * highway X, built on hwcore's HWY base (sc3netmod_hwy.c). #included by sc3netmod.c after the HWY block; runs as
 * `hwx_run(hp);` in rb_hwy (sc3netmod_rbt.c), on every highway retile and on the city-load pass.
 *
 * Shape (verify/hwx/README.md; art, lanes and the table from re/tools/netmod/hwx.py / hwx_build.py): the stock X
 * (12 cells in a 4x4, the highway along z over, the one along x under, whatever the drag order) plus, per quadrant, a
 * 270-degree loop (left turn) and an outer ramp (right turn), all one-lane slabs at deck height, in a 12x12 box.
 * Frame: (dx, dz) from the X centre cell (0, 0) = stock 15113.0; the highway along z holds dx -1 / 0, the one along
 * x dz -1 / 0. The X is never turned (the stock X always puts z over x), so the table lists every cell.
 *
 * Rule:
 *   new X     the stock 12-cell X (ids and states exact) whose four arms continue (both cells just outside the 4x4
 *             on every arm hold highway: an arm that stops there is hwt's stub T, agreed 2026-10-18), no stock
 *             interchange ring (15115..15128, Berlin's) in its 6x6. In an edit pass only (a city load never takes
 *             land). Cloverleaf when every table cell is inside the read box, the arm cells (dx / dz 2..5, -6..-3) are
 *             plain straight stock highway, every ramp cell is hwy_free and unclaimed and has no other highway beside
 *             it from outside the layout; else the clean flyover (the 12 core cells only). Task hwcap2 (owner
 *             2026-10-18, "never extend"): an arm whose drag ends ON its last junction row (dx / dz 5 or -6) holds the
 *             stock end caps there; those two cells get the CAPPED JUNCTIONS (table class 3: the junction with the
 *             stock end face, written at the cap's own state, base = the cap) and the cloverleaf is built. An arm that
 *             ends earlier leaves a junction cell empty: the clean flyover, as before task hwcap. Nothing is added
 *             past the player's drag.
 *   built     every piece names its anchor (each (piece, state) is one table cell). Per anchor, over its cells inside
 *             the read box: the X still whole (core cells hold the stock or the clean piece, the eight cells past the
 *             4x4 hold highway) -> the core is kept as the clean flyover, and the ramps too when the arm cells hold
 *             plain highway or their own piece and every ramp cell holds its piece or is free (a bulldozed ramp cell
 *             is rebuilt, as hwt does: a pass may see only part of the cloverleaf, so all-or-nothing on the ramps
 *             could not be decided per pass); arm cut -> ramps not kept (hwy_end removes them), junction cells back
 *             to plain highway, the flyover stays. X broken -> core back to the stock pieces, junction cells plain,
 *             ramps removed: the stock tiler takes over.
 *
 * Table lines (netpack manifest "highway_lines", generated by hwx_build.py manifest):
 *   hwx <piece> <state> <dx> <dz> <cls 0 junction | 1 ramp | 2 core | 3 capped junction>
 *   (a class 3 line names the junction cell (dx, dz) it replaces when that arm ends there; state = the stock cap's)
 * Off: SC3NETMOD_HWX=0.
 */

#define HWX_MAXC 128
#define HWX_MAXA 32

typedef struct { WORD piece; BYTE put, cls; short dx, dz; } HwxCell;

static HwxCell g_hwx_c[HWX_MAXC];
static int g_hwx_n, g_hwx_b0 = 99, g_hwx_b1 = -99;          /* box of the table (cells, both axes) */
static volatile LONG g_hwx_n_clover, g_hwx_n_fly, g_hwx_n_kept, g_hwx_n_broken, g_hwx_n_cut;

static const short g_hwx_core[12][4] = {                     /* dx, dz, stock id, state (STOCK.md, measured) */
    {-2, -1, 15107, 0}, {-1, -1, 15113, 2}, {0, -1, 15114, 0}, {1, -1, 15108, 2},
    {-2, 0, 15108, 0}, {-1, 0, 15114, 2}, {0, 0, 15113, 0}, {1, 0, 15107, 2},
    {-1, -2, 15150, 2}, {0, -2, 15153, 2}, {-1, 1, 15153, 0}, {0, 1, 15150, 0}};
static const signed char g_hwx_arm[8][2] = {{2, -1}, {2, 0}, {-3, -1}, {-3, 0}, {-1, 2}, {0, 2}, {-1, -3}, {0, -3}};

static void hwx_line(const char *path, const char *line) {
    long p, s, dx, dz, c;
    if (sscanf(line + 4, "%ld %ld %ld %ld %ld", &p, &s, &dx, &dz, &c) != 5 || p <= 0 || p > 0xffff || s < 0 || s > 3 ||
        dx < -16 || dx > 16 || dz < -16 || dz > 16 || c < 0 || c > 3) {
        logf("### hwx: %s: bad line '%s'", path, line);
        return;
    }
    if (g_hwx_n >= HWX_MAXC) { logf("### hwx: %s: too many cells - '%s' ignored", path, line); return; }
    g_hwx_c[g_hwx_n].piece = (WORD)p; g_hwx_c[g_hwx_n].put = (BYTE)s; g_hwx_c[g_hwx_n].cls = (BYTE)c;
    g_hwx_c[g_hwx_n].dx = (short)dx; g_hwx_c[g_hwx_n].dz = (short)dz;
    if (dx < g_hwx_b0) g_hwx_b0 = dx;
    if (dz < g_hwx_b0) g_hwx_b0 = dz;
    if (dx > g_hwx_b1) g_hwx_b1 = dx;
    if (dz > g_hwx_b1) g_hwx_b1 = dz;
    g_hwx_n++;
}

static int hwx_in(HwyPass *hp, int x, int z) { return x > hp->x0 && x < hp->x1 && z > hp->z0 && z < hp->z1; }
static int hwx_is(DWORD v, WORD id, int st) { return v && hwy_id(v) == id && hwy_st(v) == st; }

static int hwx_cell_at(int dx, int dz) {
    int k;
    for (k = 0; k < g_hwx_n; k++) if (g_hwx_c[k].cls != 3 && g_hwx_c[k].dx == dx && g_hwx_c[k].dz == dz) return k;
    return -1;
}

/* task hwcap2: the capped junction of junction cell k (-1 = none) */
static int hwx_cap_at(int k) {
    int j;
    for (j = 0; j < g_hwx_n; j++)
        if (g_hwx_c[j].cls == 3 && g_hwx_c[j].dx == g_hwx_c[k].dx && g_hwx_c[j].dz == g_hwx_c[k].dz) return j;
    return -1;
}

/* task hwcap2: the stock end cap an arm ending on junction cell k leaves there (both lanes of the row are capped) */
static void hwx_cap_stock(int k, WORD *id, int *st) {
    int dx = g_hwx_c[k].dx, dz = g_hwx_c[k].dz;
    if (dz == -1 || dz == 0) hwcap_cap_of(dx > 0 ? 1 : -1, 0, dz == -1, id, st);      /* along x: dz -1 is the lower lane */
    else hwcap_cap_of(0, dz > 0 ? 1 : -1, dx == -1, id, st);
}

/* task hwcap2: junction cell k as the arm's end: 1 = v is the stock cap there or the capped junction (-> the capped
 * junction belongs there), 0 = no */
static int hwx_capped(int k, DWORD v) {
    int j = hwx_cap_at(k), st;
    WORD id;
    if (j < 0 || !v) return 0;
    if (hwx_is(v, g_hwx_c[j].piece, g_hwx_c[j].put)) return 1;
    hwx_cap_stock(k, &id, &st);
    return hwx_is(v, id, st) && st == g_hwx_c[j].put;
}

/* plain stock straight highway of a carriageway cell: 15051 along x (dz -1 drives +x: state 2), 73 along z
 * (dx 0 drives +z: state 0); 0 = not a carriageway cell of the X's arms */
static WORD hwx_plain(int dx, int dz, int *st) {
    if ((dz == -1 || dz == 0) && dx != -1 && dx != 0) { *st = dz == -1 ? 2 : 0; return 15051; }
    if ((dx == -1 || dx == 0) && dz != -1 && dz != 0) { *st = dx == -1 ? 2 : 0; return 73; }
    return 0;
}

static int hwx_is_core(int dx, int dz) {
    int k;
    for (k = 0; k < 12; k++) if (g_hwx_core[k][0] == dx && g_hwx_core[k][1] == dz) return 1;
    return 0;
}

/* the cloverleaf's check at anchor (ax, az); existing = it is built (ramp cells may hold their piece). An arm ending ON
 * its last junction row (both cells capped) counts: those cells take the capped junctions (task hwcap2) */
static int hwx_clover(HwyPass *hp, int ax, int az, int existing, const char **why) {
    int k, j, d, x, z, st;
    for (k = 0; k < g_hwx_n; k++) {
        HwxCell *c = &g_hwx_c[k];
        x = ax + c->dx; z = az + c->dz;
        if (!hwx_in(hp, x, z)) {
            if (existing) continue;                                   /* another pass's */
            *why = "cloverleaf not inside the read box"; return 0;
        }
        if (hwy_claimed(x, z)) { *why = "a cell is claimed by another block"; return 0; }
        if (c->cls != 1) continue;
        if (existing && hwx_is(hwy_at(hp, x, z), c->piece, c->put)) continue;
        if (!hwy_free(hp, x, z)) { *why = "a quadrant is not free"; return 0; }
        for (j = 0; j < 4; j++) {                                     /* no other highway beside a ramp cell */
            int ndx = c->dx + (j == 0 ? -1 : j == 2 ? 1 : 0), ndz = c->dz + (j == 1 ? -1 : j == 3 ? 1 : 0);
            if (hwx_cell_at(ndx, ndz) >= 0 || hwx_is_core(ndx, ndz) || hwx_plain(ndx, ndz, &st)) continue;
            if (hwy_at(hp, ax + ndx, az + ndz)) { *why = "other highway beside a quadrant"; return 0; }
        }
    }
    for (d = g_hwx_b0; d <= g_hwx_b1; d++) {                          /* the four arms: plain straight highway */
        static const signed char lane[2] = {-1, 0};
        if (d >= -2 && d <= 1) continue;
        for (j = 0; j < 4; j++) {
            int dx = j < 2 ? d : lane[j - 2], dz = j < 2 ? lane[j] : d;
            WORD id = hwx_plain(dx, dz, &st);
            DWORD v;
            x = ax + dx; z = az + dz;
            if (!hwx_in(hp, x, z)) continue;
            v = hwy_at(hp, x, z);
            if (hwx_is(v, id, st)) continue;
            k = hwx_cell_at(dx, dz);
            if (existing && k >= 0 && hwx_is(v, g_hwx_c[k].piece, g_hwx_c[k].put)) continue;
            if (k >= 0 && hwx_capped(k, v)) continue;                 /* task hwcap2: the arm ends on its last junction */
            *why = !v ? "an arm ends inside the junction cells" : hwcap_is(v) ?
                   "an arm ends before its last junction row" : "an arm is not plain straight highway";
            return 0;
        }
    }
    return 1;
}

/* the X itself: core cells inside the box hold the stock piece (or the clean one when mine), the 8 cells past the
 * 4x4 hold highway. -> 1 whole */
static int hwx_x_ok(HwyPass *hp, int ax, int az, int mine) {
    int k, x, z;
    for (k = 0; k < 12; k++) {
        DWORD v;
        int c;
        x = ax + g_hwx_core[k][0]; z = az + g_hwx_core[k][1];
        if (!hwx_in(hp, x, z)) { if (mine) continue; return 0; }
        v = hwy_at(hp, x, z);
        if (hwx_is(v, (WORD)g_hwx_core[k][2], g_hwx_core[k][3])) continue;
        c = hwx_cell_at(g_hwx_core[k][0], g_hwx_core[k][1]);
        if (mine && c >= 0 && hwx_is(v, g_hwx_c[c].piece, g_hwx_c[c].put)) continue;
        return 0;
    }
    for (k = 0; k < 8; k++) {
        x = ax + g_hwx_arm[k][0]; z = az + g_hwx_arm[k][1];
        if (!hwx_in(hp, x, z)) { if (mine) continue; return 0; }
        if (!hwy_at(hp, x, z)) return 0;
    }
    return 1;
}

/* put the cells of `cls_mask` (bit 1 << cls) that lie inside the box -> cells written or kept. A junction cell where
 * its arm ends (the stock cap, or the capped junction) gets the capped junction (task hwcap2) */
static int hwx_put_all(HwyPass *hp, int ax, int az, int cls_mask) {
    int k, n = 0, x, z;
    for (k = 0; k < g_hwx_n; k++) {
        HwxCell *c = &g_hwx_c[k];
        if (c->cls == 3 || !(cls_mask & (1 << c->cls))) continue;
        x = ax + c->dx; z = az + c->dz;
        if (!hwx_in(hp, x, z)) continue;
        if (c->cls == 0 && hwx_capped(k, hwy_at(hp, x, z))) c = &g_hwx_c[hwx_cap_at(k)];
        if (hwy_put(hp, x, z, c->piece, c->put) >= 0) n++;
    }
    return n;
}

/* junction cells back to plain highway; core cells back to stock (core = 1) */
static void hwx_unput(HwyPass *hp, int ax, int az, int core) {
    int k, x, z, st;
    for (k = 0; k < g_hwx_n; k++) {
        HwxCell *c = &g_hwx_c[k];
        DWORD v;
        x = ax + c->dx; z = az + c->dz;
        if (c->cls == 1 || c->cls == 3 || !hwx_in(hp, x, z) || hwy_claimed(x, z)) continue;
        v = hwy_at(hp, x, z);
        if (!v) continue;
        if (c->cls == 0) {
            WORD id = hwx_plain(c->dx, c->dz, &st);
            if (hwx_capped(k, v)) hwx_cap_stock(k, &id, &st);      /* task hwcap2: an arm end gets its stock cap back */
            if (id) hwy_put(hp, x, z, id, st);
        } else if (core && hwx_is(v, c->piece, c->put)) {
            int j;
            for (j = 0; j < 12; j++)
                if (g_hwx_core[j][0] == c->dx && g_hwx_core[j][1] == c->dz)
                    hwy_put(hp, x, z, (WORD)g_hwx_core[j][2], g_hwx_core[j][3]);
        }
    }
}

static void hwx_run(HwyPass *hp) {
    static int cand[HWX_MAXA][3];                    /* ax, az, votes */
    int ncand = 0, x, z, k, j, ax, az;
    const char *why;
    int load = hp->who && !strcmp(hp->who, "load");
    if (!g_hwx_n || env_off("SC3NETMOD_HWX")) return;
    /* 1. interchanges already built: every piece of the table names its anchor ((piece, state) is one cell) */
    for (z = hp->z0 + 1; z < hp->z1; z++)
        for (x = hp->x0 + 1; x < hp->x1; x++) {
            DWORD v = hwy_at(hp, x, z);
            if (!v || hwy_claimed(x, z)) continue;
            for (k = 0; k < g_hwx_n; k++) if (hwx_is(v, g_hwx_c[k].piece, g_hwx_c[k].put)) break;
            if (k == g_hwx_n) continue;
            ax = x - g_hwx_c[k].dx; az = z - g_hwx_c[k].dz;
            for (j = 0; j < ncand; j++) if (cand[j][0] == ax && cand[j][1] == az) break;
            if (j == ncand) {
                if (ncand >= HWX_MAXA) continue;
                cand[j][0] = ax; cand[j][1] = az; cand[j][2] = 0;
                ncand++;
            }
            cand[j][2]++;
        }
    for (j = 0; j < ncand; j++) {
        int ramps = 0;
        ax = cand[j][0]; az = cand[j][1];
        for (k = 0; k < g_hwx_n; k++)
            if (g_hwx_c[k].cls != 2 && hwx_in(hp, ax + g_hwx_c[k].dx, az + g_hwx_c[k].dz) &&
                hwx_is(hwy_at(hp, ax + g_hwx_c[k].dx, az + g_hwx_c[k].dz), g_hwx_c[k].piece, g_hwx_c[k].put)) ramps++;
        if (hwx_x_ok(hp, ax, az, 1)) {
            if (ramps && hwx_clover(hp, ax, az, 1, &why)) {
                hwx_put_all(hp, ax, az, 7);
                InterlockedIncrement(&g_hwx_n_kept);
                continue;
            }
            if (ramps) {
                hwx_unput(hp, ax, az, 0);
                InterlockedIncrement(&g_hwx_n_cut);
                logf("hwx: %s: cloverleaf at (%d,%d): %s - ramps removed, the clean flyover stays", hp->who, ax, az, why);
            }
            hwx_put_all(hp, ax, az, 4);
            InterlockedIncrement(&g_hwx_n_kept);
            continue;
        }
        hwx_unput(hp, ax, az, 1);
        InterlockedIncrement(&g_hwx_n_broken);
        logf("hwx: %s: X at (%d,%d) broken: stock pieces back, ramps removed", hp->who, ax, az);
    }
    /* 2. new X's (edit passes only) */
    if (load) return;
    for (z = hp->z0 + 1; z < hp->z1; z++)
        for (x = hp->x0 + 1; x < hp->x1; x++) {
            int ring = 0, dx, dz;
            if (!hwx_is(hwy_at(hp, x, z), 15113, 0) || hwy_claimed(x, z)) continue;
            ax = x; az = z;
            for (k = 0; k < 12; k++)
                if (!hwx_is(hwy_at(hp, ax + g_hwx_core[k][0], az + g_hwx_core[k][1]), (WORD)g_hwx_core[k][2],
                            g_hwx_core[k][3])) break;
            if (k < 12) continue;
            for (k = 0; k < 12; k++) if (hwy_claimed(ax + g_hwx_core[k][0], az + g_hwx_core[k][1])) break;
            if (k < 12) continue;
            if (!hwx_x_ok(hp, ax, az, 0)) {
                logf("hwx: %s: X at (%d,%d) refused: an arm stops at the 4x4 (a stub X: hwt's T)", hp->who, ax, az);
                continue;
            }
            for (dx = -3; dx <= 2 && !ring; dx++)
                for (dz = -3; dz <= 2; dz++) {
                    DWORD v = hwy_at(hp, ax + dx, az + dz);
                    if (v && hwy_id(v) >= 15115 && hwy_id(v) <= 15128) { ring = 1; break; }
                }
            if (ring) { logf("hwx: %s: X at (%d,%d) refused: a stock interchange ring", hp->who, ax, az); continue; }
            k = hwx_clover(hp, ax, az, 0, &why);
            if (k) {                                    /* task hwask: the player decides (charged per ramp cell) */
                int nr = 0;
                for (j = 0; j < g_hwx_n; j++) nr += g_hwx_c[j].cls == 1;
                if (!hwask_ok(hp, HWASK_X, ax, az, 0, 15113, nr)) { k = 0; why = "the player chose the bridge"; }
            }
            if (k) {
                int n = hwx_put_all(hp, ax, az, 7);
                InterlockedIncrement(&g_hwx_n_clover);
                logf("hwx: %s: cloverleaf at (%d,%d): %d cells written", hp->who, ax, az, n);
            } else {
                int n = hwx_put_all(hp, ax, az, 4);
                InterlockedIncrement(&g_hwx_n_fly);
                logf("hwx: %s: clean flyover at (%d,%d) (%s): %d cells written", hp->who, ax, az, why, n);
            }
        }
}

static void hwx_stats(void) {
    static LONG last;
    LONG n = g_hwx_n_clover + g_hwx_n_fly + g_hwx_n_kept + g_hwx_n_broken + g_hwx_n_cut;
    if (!g_hwx_n || n == last) return;
    last = n;
    logf("stats: hwx cloverleafs built=%ld, flyovers built=%ld, kept=%ld, ramps cut=%ld, broken=%ld", g_hwx_n_clover,
         g_hwx_n_fly, g_hwx_n_kept, g_hwx_n_cut, g_hwx_n_broken);
}
