/* sc3netmod_bvx.c - boulevard junctions with avenues and with other boulevards (task bvx, 2026-10-17).
 * #included by sc3netmod.c after sc3netmod_bv.c; called from the BV block's run rule (bv_run1, lines marked task bvx).
 * Offline twin, art and lanes: re/tools/netmod/bvx.py (spans(), box_want()) with boulevard.py runs(); evidence
 * verify/bvx/.
 *
 * Along a boulevard run, a junction span is a group of consecutive columns with road beside the run. One column wide
 * = a single road (BV's own junction pieces, unchanged). Two or three wide, each side road over the whole span or
 * empty, every arm straight and clean for BVX_ARM_LEN cells = a WIDE span: an avenue (2) or a boulevard (3) crossing
 * the boulevard or ending on it. A wide span at the very end of the run with nothing beyond and arms on both sides =
 * the boulevard ends on that avenue / boulevard (end type 4 in bv_run1). The box (span columns x the three rows) gets
 * one piece per cell from its REAL edge pattern N E S W (I another box cell, A an arm, C closed), so the two runs that
 * cross in a boulevard x boulevard box write the same pieces. Each avenue arm's first cell gets 11204 with the median
 * nose (`bvxa`, as avx's arm pieces); a boulevard arm's first column comes from that boulevard's own run.
 * Table lines (netpack manifest "auto_boulevard_junctions"):
 *  `bvxb <piece> <NESW>`   a box cell piece whose edges at state 0 are N E S W (I / A / C)
 *  `bvxa <piece> <side>`   11204 (state 0) with the median nose at <side> (1 E, 3 W); placed in the cell's 11204 state
 * Saves: as their bases (box 43, noses 11204). Revert: BV's (bv_is_piece knows these pieces). Off: SC3NETMOD_BVX=0
 * (wide spans are then refused by BV as before: "not a straight single road").
 * Task avx32 (owner hand test 2026-10-21, img7): a 3-column span may have a 2-column avenue arm at one end of a side
 * (the crossing road is a boulevard on one side and an avenue on the other, or an avenue crossing one column offset),
 * and a run may end in a box with an avenue going on past it (bv_run1 end type 6). Such a side is 'L' / 'H' in the
 * bvxc lines: the arm holds the low / high end of the side in REAL coordinates (smaller x on N / S, smaller z on E / W).
 * Task avx32 (owner img12): a run ending ON a single road that crosses its last column makes that column a 1-column
 * box (bv_run1 marks it a wide T column; bvxc lines w 1 / h 1, pieces 21928..21930).
 */

#define BVX_ARM_LEN 2
#define BVX_MAX_BOX 8

typedef struct { WORD piece; char e[4]; } BvxBox;
static BvxBox g_bvx_box[BVX_MAX_BOX];
static WORD g_bvx_arm[4];                               /* by the box side at state 0: [1] E, [3] W */
/* task bvlanes: with one-way lanes a box cell's lanes depend on the whole box, not on its own edge pattern, so the
   cells are chosen by (real box width, height, sides N E S W A / C, cell i j from the box's x- z- corner) ->
   piece, state (`bvxc w h NESW i j piece state`, generated by bvlanes.py for every turn of the five box kinds).
   When any bvxc line is declared, the edge-pattern pieces (bvxb) are no longer used to choose box cells. */
#define BVX_MAX_CELL 512                                         /* task avx32: 213 lines */
typedef struct { BYTE w, h, i, j, st; char e[4]; WORD piece; } BvxCell;
static BvxCell g_bvx_cell[BVX_MAX_CELL];
static int g_bvx_ncell;
/* axis-space direction (0 -s, 1 +s, 2 -w, 3 +w) -> real edge N E S W; axis 0 real (s, w), axis 1 real (-w, s) */
static const BYTE BVX_REAL[2][4] = { { 3, 1, 0, 2 }, { 0, 2, 1, 3 } };

static void bvx_line(const char *path, const char *line) {
    unsigned long v, s;
    char e[8];
    int k;
    if (!strncmp(line, "bvxa ", 5)) {
        if (sscanf(line + 5, "%lu %lu", &v, &s) != 2 || !v || v > 0xffff || (s != 1 && s != 3) || g_base[v] != 11204) {
            logf("### bvx: %s: bad arm line or piece not a variant of 11204: '%s'", path, line);
            return;
        }
        g_bvx_arm[s] = (WORD)v;
        logf("bvx: %s: avenue arm piece %lu = 11204 with the median nose at its %s end", path, v, s == 1 ? "E" : "W");
        return;
    }
    if (!strncmp(line, "bvxc ", 5)) {                                              /* task bvlanes */
        unsigned long w, h, i, j, st;
        if (sscanf(line + 5, "%lu %lu %4s %lu %lu %lu %lu", &w, &h, e, &i, &j, &v, &st) != 7 || w < 1 || w > 3 ||
            h < 1 || h > 3 || i >= w || j >= h || st > 3 || strlen(e) != 4 || !v || v > 0xffff || !g_base[v]) {
            logf("### bvx: %s: bad box cell line or piece not a variant: '%s'", path, line);
            return;
        }
        if (g_bvx_ncell >= BVX_MAX_CELL) { logf("### bvx: %s: too many box cell lines - ignored", path); return; }
        g_bvx_cell[g_bvx_ncell].w = (BYTE)w; g_bvx_cell[g_bvx_ncell].h = (BYTE)h;
        g_bvx_cell[g_bvx_ncell].i = (BYTE)i; g_bvx_cell[g_bvx_ncell].j = (BYTE)j;
        g_bvx_cell[g_bvx_ncell].st = (BYTE)st; g_bvx_cell[g_bvx_ncell].piece = (WORD)v;
        memcpy(g_bvx_cell[g_bvx_ncell].e, e, 4);
        if (++g_bvx_ncell == 1) logf("bvx: %s: box cells chosen by box kind and position (bvxc lines)", path);
        return;
    }
    if (strncmp(line, "bvxb ", 5)) return;
    if (sscanf(line + 5, "%lu %4s", &v, e) != 2 || !v || v > 0xffff || strlen(e) != 4 || !g_base[v]) {
        logf("### bvx: %s: bad box line or piece not a variant: '%s'", path, line);
        return;
    }
    for (k = 0; k < 4; k++)
        if (e[k] != 'I' && e[k] != 'A' && e[k] != 'C') { logf("### bvx: %s: edges must be I/A/C: '%s'", path, line); return; }
    if (g_bvx_nbox >= BVX_MAX_BOX) { logf("### bvx: %s: too many box pieces - ignored", path); return; }
    g_bvx_box[g_bvx_nbox].piece = (WORD)v;
    memcpy(g_bvx_box[g_bvx_nbox].e, e, 4);
    g_bvx_nbox++;
    logf("bvx: %s: boulevard junction box piece %lu, edges N E S W %.4s at state 0", path, v, e);
}

static int bvx_cells_on(void) { return g_bvx_nbox && g_bvx_ncell; }                      /* task avx32 */

static int bvx_is_piece(WORD id) {
    int k;
    if (!id || !g_bvx_nbox) return 0;
    for (k = 0; k < g_bvx_nbox; k++) if (g_bvx_box[k].piece == id) return 1;
    for (k = 0; k < g_bvx_ncell; k++) if (g_bvx_cell[k].piece == id) return 1;      /* task bvlanes */
    return id == g_bvx_arm[1] || id == g_bvx_arm[3];
}

/* edge pattern (N E S W) -> piece << 8 | state, 0 = none (avx_box_of) */
static DWORD bvx_box_of(const char *d) {
    int k, j, e;
    for (k = 0; k < 4; k++)
        for (j = 0; j < g_bvx_nbox; j++) {
            for (e = 0; e < 4 && g_bvx_box[j].e[e] == d[(e + k) % 4]; e++) ;
            if (e == 4) return ((DWORD)g_bvx_box[j].piece << 8) | (DWORD)k;
        }
    return 0;
}

/* task bvlanes: the cell (i, j) of a w x h box with real sides e (N E S W) -> piece << 8 | state, 0 = none */
static DWORD bvx_cell_of(int w, int h, const char *e, int i, int j) {
    int k;
    for (k = 0; k < g_bvx_ncell; k++) {
        BvxCell *c = &g_bvx_cell[k];
        if (c->w == w && c->h == h && c->i == i && c->j == j && !memcmp(c->e, e, 4))
            return ((DWORD)c->piece << 8) | (DWORD)c->st;
    }
    return 0;
}

/* kind[] of columns sa..sb: 0, or 4 | arm N (1) | arm S (2) for a wide span column. -> 0 = the run is refused (*why).
   task avx32: in a 3-column span a side may hold a 2-column arm at one end (the box's side letter 'L' / 'H').
   task avx32 (owner img16): a BAD ARM (too short, road beside it) sets *bad_e = the run end nearer to the span
   (0 +s, 1 -s), so bv_run_fb can leave that end stock, and p->bja / bjb = the span (bv_parts splits there);
   any other refusal leaves *bad_e as it is */
static int bvx_spans(BvPass *p, int sa, int sb, int w0, BYTE *kind, const char **why, int *bad_e) {
    int s = sa, ja, jb, m, c, k, side, got[2], lo[2], hi[2], arm[2], ok;
    for (c = sa; c <= sb; c++) kind[c - sa] = 0;
    if (!g_bvx_nbox) return 1;
    while (s <= sb) {
        if (!bv_road(p, s, w0 - 1) && !bv_road(p, s, w0 + 3)) { s++; continue; }
        ja = s;
        while (s + 1 <= sb && (bv_road(p, s + 1, w0 - 1) || bv_road(p, s + 1, w0 + 3))) s++;
        jb = s++;
        m = jb - ja + 1;
        if (m < 2) continue;
        for (ok = 1, side = 0; side < 2; side++) {
            int w = side ? w0 + 3 : w0 - 1;
            got[side] = 0; lo[side] = hi[side] = -1;
            for (c = ja; c <= jb; c++)
                if (bv_road(p, c, w)) { got[side]++; if (lo[side] < 0) lo[side] = c; hi[side] = c; }
            /* task avx32: 2 of 3, side by side = an avenue at one end of the side */
            if (got[side] && got[side] != m && !(m == 3 && got[side] == 2 && hi[side] == lo[side] + 1)) ok = 0;
        }
        if (!ok) continue;                                  /* staggered: BV's per-column rule */
        if (m > 3) { *why = "road more than 3 wide beside the boulevard"; return 0; }
        for (side = 0; side < 2; side++) {
            int w = side ? w0 + 3 : w0 - 1, d = side ? 1 : -1;
            arm[side] = got[side] != 0;
            if (!arm[side]) continue;
            for (k = 0; k < BVX_ARM_LEN; k++) {
                for (c = lo[side]; c <= hi[side]; c++)
                    if (!bv_road(p, c, w + d * k))
                        { *why = "avenue / boulevard arm shorter than 2"; *bad_e = ja - sa <= sb - jb;
                          p->bja = ja; p->bjb = jb; return 0; }
                if (bv_road(p, lo[side] - 1, w + d * k) || bv_road(p, hi[side] + 1, w + d * k))
                    { *why = "avenue / boulevard arm has road beside it"; *bad_e = ja - sa <= sb - jb;
                          p->bja = ja; p->bjb = jb; return 0; }
            }
        }
        for (side = 0; side < 2; side++) {                  /* task bvlanes: an avenue arm must convert (program rule) */
            int w = side ? w0 + 4 : w0 - 2;                 /* the band cell past the arm's nose */
            if (got[side] != 2) continue;
            if (!BV_BAND_OK(bv_rx(p->axis, lo[side], w), bv_rz(p->axis, lo[side], w), bv_side(p->axis, side ? 2 : -2)))
                { *why = "an avenue arm that would stay two-way"; return 0; }
            if (p->natt < 8) {                              /* the nose cell and the band cell past it */
                int wn = side ? w0 + 3 : w0 - 1;
                p->att[p->natt][0] = bv_rx(p->axis, lo[side], wn); p->att[p->natt][1] = bv_rz(p->axis, lo[side], wn);
                p->att[p->natt][2] = bv_rx(p->axis, lo[side], w); p->att[p->natt][3] = bv_rz(p->axis, lo[side], w);
                p->att[p->natt][4] = bv_side(p->axis, side ? 2 : -2);
                p->natt++;
            }
        }
        for (c = ja; c <= jb; c++) kind[c - sa] = (BYTE)(4 | arm[0] | (arm[1] << 1));
    }
    return 1;
}

/* task avx32: the real side letter of a box side from its three / two cells beyond (axis space, arm[] = road there):
   'A' all, 'C' none, 'L' / 'H' the arm holds the low / high end in real coordinates (x on N / S, z on E / W) */
static char bvx_letter(int axis, int e, int n, const int (*cs)[2], const int *arm) {
    int i, got = 0, amin = 0x7fffffff, fmin = 0x7fffffff;
    for (i = 0; i < n; i++) {
        int rx = bv_rx(axis, cs[i][0], cs[i][1]), rz = bv_rz(axis, cs[i][0], cs[i][1]), v = (e == 0 || e == 2) ? rx : rz;
        if (arm[i]) { got++; if (v < amin) amin = v; } else if (v < fmin) fmin = v;
    }
    return !got ? 'C' : got == n ? 'A' : fmin > amin ? 'L' : 'H';
}

static void bvx_put(BvPass *p, int x, int z, DWORD want) {
    if (p->n >= DAV_MAX_CELLS) return;
    p->cell[p->n].x = x;
    p->cell[p->n].z = z;
    p->cell[p->n].want = want;
    p->n++;
}

/* the boxes of every wide span of run sa..sb (+ avenue noses). lo_tee / hi_tee: the run ends on the crossing road at
   its -s / +s end (that box side is closed). lo_av / hi_av (task avx32): 1 + the first row w - w0 of the avenue that
   goes on past the -s / +s end (the run ends in the box), 0 none. -> 0 when a pattern has no piece */
static int bvx_boxes(BvPass *p, int sa, int sb, int w0, const BYTE *kind, int lo_tee, int hi_tee, int lo_av, int hi_av) {
    int ja, jb, s, w, dir, i;
    for (ja = sa; ja <= sb; ja++) {
        char side[4];
        int cs[3][2], arm[3], part = 0;
        if (!(kind[ja - sa] & 4) || (ja > sa && (kind[ja - 1 - sa] & 4))) continue;
        for (jb = ja; jb + 1 <= sb && (kind[jb + 1 - sa] & 4); jb++) ;
        for (dir = 0; dir < 4; dir++) {                     /* task avx32: per side, from the cells beyond it */
            int n = 0, av = 0, closed = 0;
            if (dir < 2) {                                  /* -s (0) / +s (1): the three rows past the box */
                s = dir ? jb + 1 : ja - 1;
                closed = dir ? (hi_tee && jb == sb) : (lo_tee && ja == sa);
                av = dir ? (jb == sb ? hi_av : 0) : (ja == sa ? lo_av : 0);
                for (w = w0; w <= w0 + 2; w++, n++) {
                    cs[n][0] = s; cs[n][1] = w;
                    arm[n] = !closed && (!av || w - w0 == av - 1 || w - w0 == av);
                }
            } else {                                        /* -w (2) / +w (3): the span's columns beside the box */
                w = dir == 2 ? w0 - 1 : w0 + 3;
                for (s = ja; s <= jb; s++, n++) { cs[n][0] = s; cs[n][1] = w; arm[n] = bv_road(p, s, w); }
            }
            side[dir] = bvx_letter(p->axis, BVX_REAL[p->axis][dir], n, (const int (*)[2])cs, arm);
            part |= side[dir] == 'L' || side[dir] == 'H';
        }
        if (g_bvx_ncell) {                                                         /* task bvlanes */
            char re[4];
            int bx0 = 0x7fffffff, bz0 = 0x7fffffff, bx1 = -0x7fffffff, bz1 = -0x7fffffff;
            for (dir = 0; dir < 4; dir++) re[BVX_REAL[p->axis][dir]] = side[dir];
            for (s = ja; s <= jb; s++)
                for (w = w0; w <= w0 + 2; w++) {
                    int x = bv_rx(p->axis, s, w), z = bv_rz(p->axis, s, w);
                    if (x < bx0) bx0 = x;
                    if (x > bx1) bx1 = x;
                    if (z < bz0) bz0 = z;
                    if (z > bz1) bz1 = z;
                }
            for (s = ja; s <= jb; s++)
                for (w = w0; w <= w0 + 2; w++) {
                    int x = bv_rx(p->axis, s, w), z = bv_rz(p->axis, s, w);
                    DWORD v = bvx_cell_of(bx1 - bx0 + 1, bz1 - bz0 + 1, re, x - bx0, z - bz0);
                    if (!v) return 0;
                    bvx_put(p, x, z, v);
                }
        } else {
            if (part) return 0;                             /* task avx32: edge-pattern pieces have no partial side */
            for (s = ja; s <= jb; s++)
                for (w = w0; w <= w0 + 2; w++) {
                    char d[4];
                    DWORD v;
                    d[BVX_REAL[p->axis][0]] = s > ja ? 'I' : side[0];
                    d[BVX_REAL[p->axis][1]] = s < jb ? 'I' : side[1];
                    d[BVX_REAL[p->axis][2]] = w > w0 ? 'I' : side[2];
                    d[BVX_REAL[p->axis][3]] = w < w0 + 2 ? 'I' : side[3];
                    if (!(v = bvx_box_of(d))) return 0;
                    bvx_put(p, bv_rx(p->axis, s, w), bv_rz(p->axis, s, w), v);
                }
        }
        for (dir = 2; dir < 4; dir++) {                     /* an avenue arm (2 columns): its two cells beside the box */
            int e = BVX_REAL[p->axis][dir], wa = dir == 2 ? w0 - 1 : w0 + 3, c0 = -1, c1 = -1, nc = 0;
            for (s = ja; s <= jb; s++) if (bv_road(p, s, wa)) { if (c0 < 0) c0 = s; c1 = s; nc++; }
            if (nc != 2) continue;
            for (i = 0; i < 2; i++) {
                int x0 = bv_rx(p->axis, c0, wa), z0 = bv_rz(p->axis, c0, wa), x1 = bv_rx(p->axis, c1, wa),
                    z1 = bv_rz(p->axis, c1, wa), cx = i ? x1 : x0, cz = i ? z1 : z0, first, st, d0;
                /* "first" = the smaller x (arm along z, e N / S) or the smaller z (arm along x): avx.py half_state */
                first = (e == 0 || e == 2) ? cx == (x0 < x1 ? x0 : x1) : cz == (z0 < z1 ? z0 : z1);
                st = (e == 1 || e == 3) ? (first ? 2 : 0) : (first ? 1 : 3);
                d0 = (((e + 2) % 4) - st + 4) % 4;
                if (!g_bvx_arm[d0]) return 0;
                bvx_put(p, cx, cz, ((DWORD)g_bvx_arm[d0] << 8) | (DWORD)st);
            }
        }
    }
    return 1;
}
