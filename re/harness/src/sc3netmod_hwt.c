/* sc3netmod_hwt.c - the HWT block of sc3netmod.dll (task hwt, highway program 2026-10-18): a highway T that connects
 * every movement, built on hwcore's HWY base (sc3netmod_hwy.c). #included by sc3netmod.c after the HWY block; runs as
 * `hwt_run(hp);` in rb_hwy (sc3netmod_rbt.c), so on every highway retile and on the city-load pass.
 *
 * Shape (verify/hwt/README.md, art and lanes from re/tools/netmod/hwt_paint.py): a TRUMPET. Stem frame = the stem
 * arrives from -z; SB column dx 0 (runs -z), NB column dx 1 (runs +z); through highway rows dz 0 (runs +x) and dz 1
 * (runs -x). The stem's two lanes bridge over both carriageways; on the far side NB's ramp loops into the far
 * carriageway and an outer ramp brings it back over the bridge into the stem; on the stem side two right-turn ramps.
 * A T turned r quarter turns: world cell = anchor + R^r(dx, dz), R(x, z) = (-z, x) (hwy_rot), piece state = r.
 *
 * Triggers (both give the same T, every rotation):
 *   gesture 1  the stem's stock end caps beside the side of a straight through highway: frame (0,-1) = 11235 / 15053,
 *              (1,-1) = 11237 / 15054 (a stem along z ends in 11235 / 11237, along x in 15053 / 15054, measured)
 *   gesture 2  the stock stub X: X centre 15113 / 15114 at (0..1, 0..1), arms 15150 / 15153 at (0..1, -1) and (0..1, 2),
 *              15107 / 15108 at (-1, 0..1) and (2, 0..1), and NO highway at (0..1, 3) (hwx takes an X only when all
 *              four arms continue: agreed 2026-10-18)
 * and then: the stem straight from dz -2 to one past the T's last stem cell, the through highway straight one past the
 * T's cells both ways, every cell of the T inside the pass's read box, its land cells hwy_free and unclaimed, no other
 * highway touching a land cell from outside the T. Task hwcap2 (owner 2026-10-18, "never extend"): a highway may END
 * there (sc3netmod_hwcap.c hwcap_end): a cell outside the T's own cells may hold its stock end cap or lie past it; a
 * T cell may hold the cap only where the package has a CAPPED twin for it (`hwtc` line: the T piece with the stock end
 * face, same state r, saved as the stock cap), which the T then writes there. A T cell past the end refuses the T.
 * Nothing is added past the player's drag. Full T only: when the far side is not free the stem keeps its caps
 * and nothing is built (owner call 2026-10-18). The right-in / right-out set (cells tagged set 2: NB -> EB and EB -> SB
 * only) stays in the tables and in the code behind HWT_RIO = 0; Ts already built with it are still recognised.
 * A built T is recognised by vote: each of its pieces names an anchor (id -> frame cell, state -> r); an anchor with
 * HWT_MINVOTE agreeing pieces is a T (a stock retile can leave a rewritten highway cell in another state). Each of its
 * cells inside the box must
 * hold its piece, or (a rewritten highway cell) some highway, or (a land cell) be free; then every cell is re-put
 * (after a stock retile changed some) and kept. Otherwise nothing is kept and hwy_end reverts the pieces. So the T
 * goes away when its stem or through highway is cut (hwt_break puts plain stock highway back, and removes a stem stub
 * left against the through highway). A bulldozed ramp cell is free again: it is rebuilt.
 * Task hwtdel (owner bug 2026-10-22, "deleting adjacent highway pieces breaks the T"): an anchor with fewer than
 * HWT_MINVOTE pieces inside the box is recounted over the whole footprint (map reads past the box), so a pass that
 * only grazes a T keeps it instead of reverting the cells it sees; a kept T also keeps its cells outside the box and
 * the plain highway cells of its frame (hwt_band) for hwy_end's re-place, and puts plain highway back over a 15149
 * found in those.
 *
 * Table lines (netpack manifest "highway_lines", generated by hwt_build.py manifest):
 *   hwt <piece> <dx> <dz> <land 0|1> <sets 1 full | 2 rio | 3 both>
 *   hwtc <capped piece> <dx> <dz>     the capped twin of the T's highway cell (dx, dz) (task hwcap2)
 * Off: SC3NETMOD_HWT=0.
 */

#define HWT_MAXC 96
#define HWT_MAXK 8
#define HWT_RIO 0        /* owner 2026-10-18: far side built up -> leave the T stock; 1 = build right-in / right-out */

typedef struct { WORD piece; short dx, dz; BYTE land, sets; } HwtCell;

static HwtCell g_hwt_c[HWT_MAXC];
static int g_hwt_n;
static struct { WORD piece; short k; } g_hwt_k[HWT_MAXK];       /* task hwcap2: capped twin -> T cell index */
static int g_hwt_nk;
static volatile LONG g_hwt_n_full, g_hwt_n_rio, g_hwt_n_kept, g_hwt_n_broken;

static void hwt_line(const char *path, const char *line) {
    long p, dx, dz, l, s;
    if (!strncmp(line, "hwtc ", 5)) {                                /* task hwcap2: hwtc <capped> <dx> <dz> */
        int k;
        if (sscanf(line + 5, "%ld %ld %ld", &p, &dx, &dz) != 3 || p <= 0 || p > 0xffff || g_hwt_nk >= HWT_MAXK) {
            logf("### hwt: %s: bad line '%s'", path, line);
            return;
        }
        for (k = 0; k < g_hwt_n; k++)
            if (g_hwt_c[k].dx == dx && g_hwt_c[k].dz == dz && !g_hwt_c[k].land) break;
        if (k == g_hwt_n) { logf("### hwt: %s: '%s' names no highway cell of the T (hwt lines first)", path, line); return; }
        g_hwt_k[g_hwt_nk].piece = (WORD)p; g_hwt_k[g_hwt_nk].k = (short)k;
        g_hwt_nk++;
        return;
    }
    if (sscanf(line + 4, "%ld %ld %ld %ld %ld", &p, &dx, &dz, &l, &s) != 5 || p <= 0 || p > 0xffff || dx < -16 ||
        dx > 16 || dz < -16 || dz > 16 || l < 0 || l > 1 || s < 1 || s > 3) {
        logf("### hwt: %s: bad line '%s'", path, line);
        return;
    }
    if (g_hwt_n >= HWT_MAXC) { logf("### hwt: %s: too many cells - '%s' ignored", path, line); return; }
    g_hwt_c[g_hwt_n].piece = (WORD)p; g_hwt_c[g_hwt_n].dx = (short)dx; g_hwt_c[g_hwt_n].dz = (short)dz;
    g_hwt_c[g_hwt_n].land = (BYTE)l; g_hwt_c[g_hwt_n].sets = (BYTE)s;
    g_hwt_n++;
}

static int hwt_cell_of(WORD id) {
    int k;
    for (k = 0; k < g_hwt_n; k++) if (g_hwt_c[k].piece == id) return k;
    for (k = 0; k < g_hwt_nk; k++) if (g_hwt_k[k].piece == id) return g_hwt_k[k].k;
    return -1;
}

static void hwt_world(int ax, int az, int r, int dx, int dz, int *x, int *z) {
    hwy_rot(r, &dx, &dz);
    *x = ax + dx; *z = az + dz;
}

static int hwt_inbox(HwyPass *hp, int x, int z) { return x >= hp->x0 && x <= hp->x1 && z >= hp->z0 && z <= hp->z1; }

/* heading of a stock straight highway cell (73 along z, 15051 along x; state 0 / 2, NET_LANES.md 1.1, measured) */
static int hwt_head(DWORD v, int *hx, int *hz) {
    WORD id = hwy_id(v);
    int s = hwy_st(v);
    if (!v) return 0;
    if (id == 15051 && (s == 0 || s == 2)) { *hx = s == 2 ? 1 : -1; *hz = 0; return 1; }
    if (id == 73 && (s == 0 || s == 2)) { *hx = 0; *hz = s == 0 ? 1 : -1; return 1; }
    return 0;
}

/* the frame heading a highway cell of the T carries before it is converted: through rows and stem columns */
static void hwt_frame_head(int dx, int dz, int *hx, int *hz) {
    if (dz == 0) { *hx = 1; *hz = 0; }
    else if (dz == 1) { *hx = -1; *hz = 0; }
    else if (dx == 0) { *hx = 0; *hz = -1; }
    else { *hx = 0; *hz = 1; }
    (void)dx;
}

static int hwt_straight(HwyPass *hp, int ax, int az, int r, int dx, int dz) {
    int x, z, hx, hz, wx, wz;
    hwt_world(ax, az, r, dx, dz, &x, &z);
    if (!hwt_inbox(hp, x, z) || !hwt_head(hwy_at(hp, x, z), &hx, &hz)) return 0;
    hwt_frame_head(dx, dz, &wx, &wz);
    hwy_rot(r, &wx, &wz);
    return hx == wx && hz == wz;
}

/* task hwcap2: the frame step out of the T along the highway a T highway cell lies on (stem: -z, through: the side) */
static void hwt_out(int dx, int dz, int *sx, int *sz) {
    if (dz == 0 || dz == 1) { *sx = dx < 0 ? -1 : 1; *sz = 0; }
    else { *sx = 0; *sz = -1; }
}

static WORD hwt_twin(int k) {
    int j;
    for (j = 0; j < g_hwt_nk; j++) if (g_hwt_k[j].k == k) return g_hwt_k[j].piece;
    return 0;
}

/* task hwcap2: T highway cell k at turn r, holding v, is where its highway ends: v is the capped twin (state r) or that
 * highway's stock end cap -> the piece to write there (its capped twin), else 0 */
static WORD hwt_capped(int k, int r, DWORD v) {
    WORD tw = hwt_twin(k);
    int sx, sz, dx, dz;
    if (!tw || !v) return 0;
    if (hwy_id(v) == tw && hwy_st(v) == r) return tw;
    hwt_out(g_hwt_c[k].dx, g_hwt_c[k].dz, &sx, &sz);
    hwy_rot(r, &sx, &sz);
    return hwcap_dir(v, &dx, &dz) && dx == sx && dz == sz ? tw : 0;
}

/* task hwcap2: the stock end cap of T highway cell (dx, dz) at turn r (its highway ending there) */
static void hwt_cap_stock(int r, int dx, int dz, WORD *id, int *st) {
    int sx, sz, px, pz;
    hwt_out(dx, dz, &sx, &sz);
    if (sz == 0) { px = 0; pz = dz == 0 ? 1 : -1; }                  /* toward the other lane of the pair */
    else { px = dx == 0 ? 1 : -1; pz = 0; }
    hwy_rot(r, &sx, &sz);
    hwy_rot(r, &px, &pz);
    hwcap_cap_of(sx, sz, px + pz > 0, id, st);
}

static int hwt_in_set(int dx, int dz, int set) {
    int k;
    for (k = 0; k < g_hwt_n; k++)
        if ((g_hwt_c[k].sets & set) && g_hwt_c[k].dx == dx && g_hwt_c[k].dz == dz) return 1;
    return 0;
}

static int hwt_is_id(DWORD v, WORD a, WORD b) { return v && (hwy_id(v) == a || hwy_id(v) == b); }

/* plain stock piece for a world heading */
static void hwt_plain(int hx, int hz, WORD *id, int *st) {
    if (hz == 0) { *id = 15051; *st = hx > 0 ? 2 : 0; }
    else { *id = 73; *st = hz > 0 ? 0 : 2; }
}

/* a straight cell of the stem / through highway, or (task hwcap2) where that highway ends: (sx, sz) = the frame step
 * away from the T. A cell that is not one of the T's own may hold the end cap or lie past it; a T cell may only hold
 * the cap, and only when it has a capped twin */
static int hwt_straight_or_end(HwyPass *hp, int ax, int az, int r, int set, int dx, int dz, int sx, int sz) {
    int x, z, e, k;
    if (hwt_straight(hp, ax, az, r, dx, dz)) return 1;
    hwt_world(ax, az, r, dx, dz, &x, &z);
    if (!hwt_inbox(hp, x, z) || hwy_claimed(x, z)) return 0;
    hwy_rot(r, &sx, &sz);
    e = hwcap_end(hp, x, z, sx, sz);
    if (!e) return 0;
    for (k = 0; k < g_hwt_n; k++)
        if ((g_hwt_c[k].sets & set) && !g_hwt_c[k].land && g_hwt_c[k].dx == dx && g_hwt_c[k].dz == dz)
            return e == 1 && hwt_capped(k, r, hwy_at(hp, x, z)) != 0;
    return 1;
}

/* the strict check of a NEW T at (ax, az, r): 1 = build it */
static int hwt_check(HwyPass *hp, int ax, int az, int r, int gesture, int set, const char **why) {
    int k, x, z, dx, dz, tx0 = 99, tx1 = -99, sz0 = 0;
    for (k = 0; k < g_hwt_n; k++) {
        HwtCell *c = &g_hwt_c[k];
        if (!(c->sets & set)) continue;
        hwt_world(ax, az, r, c->dx, c->dz, &x, &z);
        if (x <= hp->x0 || x >= hp->x1 || z <= hp->z0 || z >= hp->z1) { *why = "T not inside the read box"; return 0; }
        if (c->dz == 0 || c->dz == 1) { if (c->dx < tx0) tx0 = c->dx; if (c->dx > tx1) tx1 = c->dx; }
        if (c->dz < 0 && (c->dx == 0 || c->dx == 1) && c->dz < sz0) sz0 = c->dz;
    }
    if (tx0 > tx1) { *why = "no cells in this set"; return 0; }
    if (gesture == 1) {
        hwt_world(ax, az, r, 0, -1, &x, &z);
        if (!hwt_is_id(hwy_at(hp, x, z), 11235, 15053)) { *why = "no cap"; return 0; }
        hwt_world(ax, az, r, 1, -1, &x, &z);
        if (!hwt_is_id(hwy_at(hp, x, z), 11237, 15054)) { *why = "no cap pair"; return 0; }
    } else {
        static const signed char xc[12][2] = {{0, 0}, {1, 0}, {0, 1}, {1, 1}, {0, -1}, {1, -1}, {0, 2}, {1, 2},
                                              {-1, 0}, {-1, 1}, {2, 0}, {2, 1}};
        for (k = 0; k < 12; k++) {
            DWORD v;
            hwt_world(ax, az, r, xc[k][0], xc[k][1], &x, &z);
            v = hwy_at(hp, x, z);
            if (k < 4 ? !hwt_is_id(v, 15113, 15114) : k < 8 ? !hwt_is_id(v, 15150, 15153) : !hwt_is_id(v, 15107, 15108)) {
                *why = "not a stock X"; return 0;
            }
        }
        for (k = 0; k < 2; k++) {
            hwt_world(ax, az, r, k, 3, &x, &z);
            if (hwy_at(hp, x, z)) { *why = "far arm continues: a full X (hwx)"; return 0; }
        }
    }
    /* the through highway. task hwtee: where the stem meets it first (no through highway there = a lone end, silent),
     * then along it: a through highway that ends inside the T's reach is logged (owner bug 3, 2026-10-21) */
    for (dx = 0; dx <= 1 && gesture == 1; dx++)                          /* where the stem meets it: never carried on */
        if (!hwt_straight(hp, ax, az, r, dx, 0) || !hwt_straight(hp, ax, az, r, dx, 1)) { *why = "through highway"; return 0; }
    for (dz = -2; dz >= sz0 - 1; dz--)                                    /* the stem behind the end (task hwtee: moved) */
        if (!hwt_straight_or_end(hp, ax, az, r, set, 0, dz, 0, -1) || !hwt_straight_or_end(hp, ax, az, r, set, 1, dz, 0, -1)) {
            *why = gesture == 1 ? "the stem must run straight 4 cells back from the through highway, nothing past its end" : "stem";
            return 0;
        }
    for (dx = tx0 - 1; dx <= tx1 + 1; dx++) {
        if ((gesture == 2 && dx >= -1 && dx <= 2) || (dx >= 0 && dx <= 1)) continue;
        if (!hwt_straight_or_end(hp, ax, az, r, set, dx, 0, dx < 0 ? -1 : 1, 0) ||
            !hwt_straight_or_end(hp, ax, az, r, set, dx, 1, dx < 0 ? -1 : 1, 0)) {
            *why = dx < 0 ? "the through highway must run on 2 cells left of the stem (seen from the stem), nothing past its end"
                          : "the through highway must run on 6 cells right of the stem (seen from the stem), nothing past its end";
            return 0;
        }
    }
    for (k = 0; k < g_hwt_n; k++) {                                      /* the cells */
        HwtCell *c = &g_hwt_c[k];
        int j;
        if (!(c->sets & set)) continue;
        hwt_world(ax, az, r, c->dx, c->dz, &x, &z);
        if (hwy_claimed(x, z)) { *why = "cell claimed by another block"; return 0; }
        if (!c->land) continue;
        if (gesture == 2 && c->dz == 2 && (c->dx == 0 || c->dx == 1)) continue;   /* the stub arm: an X arm cell */
        if (!hwy_free(hp, x, z)) { *why = c->dz >= 2 ? "far side not free" : "stem side not free"; return 0; }
        for (j = 0; j < 4; j++) {                                        /* no other highway touching it */
            int ndx = c->dx + (j == 0 ? -1 : j == 2 ? 1 : 0), ndz = c->dz + (j == 1 ? -1 : j == 3 ? 1 : 0), nx, nz;
            if (hwt_in_set(ndx, ndz, set) || ndz == 0 || ndz == 1 || (ndz < 0 && (ndx == 0 || ndx == 1))) continue;
            if (gesture == 2 && ndz == 2 && (ndx == 0 || ndx == 1)) continue;
            hwt_world(ax, az, r, ndx, ndz, &nx, &nz);
            if (hwy_at(hp, nx, nz)) { *why = c->dz >= 2 ? "far side touches other highway" : "stem side touches other highway"; return 0; }
        }
    }
    return 1;
}

static void hwt_build(HwyPass *hp, int ax, int az, int r, int gesture, int set) {
    int k, x, z, n = 0, bad = 0, ncap = 0;
    for (k = 0; k < g_hwt_n; k++) {
        HwtCell *c = &g_hwt_c[k];
        WORD id;
        if (!(c->sets & set)) continue;
        hwt_world(ax, az, r, c->dx, c->dz, &x, &z);
        id = c->land ? 0 : hwt_capped(k, r, hwy_at(hp, x, z));          /* task hwcap2: its highway ends here */
        if (id) ncap++;
        if (hwy_put(hp, x, z, id ? id : c->piece, r) < 0) bad++; else n++;
    }
    if (gesture == 2) {                     /* X cells the T does not use go back to plain through highway */
        static const signed char xc[4][2] = {{-1, 0}, {-1, 1}, {2, 0}, {2, 1}};
        for (k = 0; k < 4; k++) {
            int hx, hz, st;
            WORD id;
            if (hwt_in_set(xc[k][0], xc[k][1], set)) continue;
            hwt_frame_head(xc[k][0], xc[k][1], &hx, &hz);
            hwy_rot(r, &hx, &hz);
            hwt_plain(hx, hz, &id, &st);
            hwt_world(ax, az, r, xc[k][0], xc[k][1], &x, &z);
            hwy_put(hp, x, z, id, st);
        }
    }
    InterlockedIncrement(set == 1 ? &g_hwt_n_full : &g_hwt_n_rio);
    logf("hwt: %s: %s T at anchor (%d,%d) turn %d from %s: %d cells written (%d capped)%s", hp->who,
         set == 1 ? "full" : "right-in/right-out", ax, az, r, gesture == 1 ? "the stem's end caps" : "a stub X", n, ncap,
         bad ? " (### some cells refused)" : "");
}

/* task hwtdel: cell k of a T at turn r holds its own piece (or its capped twin) */
static int hwt_is_own(int k, int r, DWORD v) {
    return v && hwy_st(v) == r && (hwy_id(v) == g_hwt_c[k].piece || (!g_hwt_c[k].land && hwy_id(v) == hwt_twin(k)));
}

/* task hwtdel: votes for anchor (ax, az, r) over the T's WHOLE footprint, cells outside the read box read from the map.
 * A pass whose box only grazes a T (owner bug 2026-10-22: a pass over the cloverleaf beside it held one T cell) saw
 * fewer than HWT_MINVOTE pieces, so hwy_end reverted the cells it did see; that stock retile re-tiled the highway run
 * through the T and left 15149 in it. */
static int hwt_votes(HwyPass *hp, int ax, int az, int r, int *sets) {
    int k, x, z, n = 0;
    for (k = 0; k < g_hwt_n; k++) {
        hwt_world(ax, az, r, g_hwt_c[k].dx, g_hwt_c[k].dz, &x, &z);
        if (hwt_is_own(k, r, hwy_rd(hp, x, z))) { n++; *sets |= g_hwt_c[k].sets | (g_hwt_c[k].sets == 1 ? 4 : 0); }
    }
    return n;
}

/* task hwtdel: the highway cells of the T's frame that the T leaves stock (through rows dx tx0..tx1, stem columns dz
 * sz0..-1, minus the T's own cells): kept, so a revert retile elsewhere in the pass is undone there too, and a 15149
 * left in one (a stock retile through the T, the owner's saved city) put back as plain highway, or the stock end cap
 * where its highway ends (the next cell out holds none). Cells outside the read box are only kept. */
static int hwt_gap_cap(HwyPass *hp, int ax, int az, int r, int dx, int dz, WORD *id, int *st);
static void hwt_band(HwyPass *hp, int ax, int az, int r, int set) {
    int k, x, z, dx, dz, tx0 = 99, tx1 = -99, sz0 = 0, i;
    for (k = 0; k < g_hwt_n; k++) {
        HwtCell *c = &g_hwt_c[k];
        if (!(c->sets & set)) continue;
        if (c->dz == 0 || c->dz == 1) { if (c->dx < tx0) tx0 = c->dx; if (c->dx > tx1) tx1 = c->dx; }
        if (c->dz < 0 && (c->dx == 0 || c->dx == 1) && c->dz < sz0) sz0 = c->dz;
    }
    tx0 -= 2; tx1 += 2; sz0 -= 2;                       /* 2 past the T: a cut right past it */
    for (i = 0; i < 2 * (tx1 - tx0 + 1) + 2 * -sz0; i++) {
        DWORD v;
        int past;
        if (i < 2 * (tx1 - tx0 + 1)) { dx = tx0 + i / 2; dz = i & 1; past = dx < tx0 + 2 || dx > tx1 - 2; }
        else { dx = i & 1; dz = -1 - (i - 2 * (tx1 - tx0 + 1)) / 2; past = dz < sz0 + 2; }
        if (hwt_in_set(dx, dz, set)) continue;
        hwt_world(ax, az, r, dx, dz, &x, &z);
        if (past) {                                       /* past the T only a 15149 next to a cut: its end cap */
            WORD id;
            int st;
            v = hwy_rd(hp, x, z);
            if (v && hwy_id(v) == 15149 && !(x <= hp->x0 || x >= hp->x1 || z <= hp->z0 || z >= hp->z1) && !hwy_claimed(x, z) &&
                hwt_gap_cap(hp, ax, az, r, dx, dz, &id, &st) && hwy_put(hp, x, z, id, st) > 0)
                logf("hwt: %s: T at anchor (%d,%d) turn %d: 15149 at (%d,%d) next to a cut -> cap %u.%d", hp->who, ax, az, r, x, z, id, st);
            continue;
        }
        if (x <= hp->x0 || x >= hp->x1 || z <= hp->z0 || z >= hp->z1) {
            v = hwy_rd(hp, x, z);
            if (v && hwy_id(v) != 15149) hwy_keep_far(hp, x, z, v);
            continue;
        }
        v = hwy_at(hp, x, z);
        if (!v || hwy_claimed(x, z)) continue;
        if (hwy_id(v) == 15149) {
            int sx, sz, hx, hz, st;
            WORD id;
            hwt_out(dx, dz, &sx, &sz);
            hwy_rot(r, &sx, &sz);
            if (hwy_rd(hp, x + sx, z + sz)) {
                hwt_frame_head(dx, dz, &hx, &hz);
                hwy_rot(r, &hx, &hz);
                hwt_plain(hx, hz, &id, &st);
            } else hwt_cap_stock(r, dx, dz, &id, &st);
            if (hwy_put(hp, x, z, id, st) > 0)
                logf("hwt: %s: T at anchor (%d,%d) turn %d: 15149 at (%d,%d) -> %u.%d", hp->who, ax, az, r, x, z, id, st);
        } else hwy_keep(hp, x, z);
    }
}

/* a T already built: relaxed check over its cells inside the box, then re-put + keep (task hwtdel: its cells outside
   the box are kept too, for the re-place after the reverts) */
static int hwt_existing(HwyPass *hp, int ax, int az, int r, int set) {
    int k, x, z, mine = 0;
    for (k = 0; k < g_hwt_n; k++) {
        HwtCell *c = &g_hwt_c[k];
        DWORD v;
        if (!(c->sets & set)) continue;
        hwt_world(ax, az, r, c->dx, c->dz, &x, &z);
        if (x <= hp->x0 || x >= hp->x1 || z <= hp->z0 || z >= hp->z1) {   /* outside: not this pass's to judge */
            if (hwt_is_own(k, r, hwy_rd(hp, x, z))) mine++;              /* task hwtdel: a T the box only grazes */
            continue;
        }
        if (hwy_claimed(x, z)) return 0;
        v = hwy_at(hp, x, z);
        if (v && hwy_id(v) == c->piece && hwy_st(v) == r) { mine++; continue; }
        if (!c->land && v && hwy_id(v) == hwt_twin(k) && hwy_st(v) == r) { mine++; continue; }   /* task hwcap2 */
        if (!c->land && v) continue;                                      /* a rewritten highway cell, re-tiled */
        if (v && hwt_cell_of(hwy_id(v)) >= 0) return 0;                  /* a land cell holding another piece */
        if (c->land && !v && hwy_free(hp, x, z)) continue;               /* a ramp cell to (re)write */
        return 0;
    }
    if (!mine) return 0;
    for (k = 0; k < g_hwt_n; k++) {
        HwtCell *c = &g_hwt_c[k];
        WORD id;
        if (!(c->sets & set)) continue;
        hwt_world(ax, az, r, c->dx, c->dz, &x, &z);
        id = c->land ? 0 : hwt_capped(k, r, hwy_rd(hp, x, z));          /* task hwcap2: its highway ends here */
        hwy_put(hp, x, z, id ? id : c->piece, r);       /* task hwtdel: past the box hwy_put only keeps a right cell */
    }
    hwt_band(hp, ax, az, r, set);                                        /* task hwtdel */
    InterlockedIncrement(&g_hwt_n_kept);
    return 1;
}

/* a T that no longer qualifies: put plain stock highway back into the highway cells it rewrote (the land cells are
 * hwy_end's to remove). Measured 2026-10-18: left to the stock retile, a stem stub against the through highway's side
 * and the through cells beside it became 15149 "Highway Construction" (the stock side-hit result), and so did caps
 * written there, after hwy_end's 3x3 retiles. So:
 *   stem cut inside the T (a stem cell of the T holds no highway): the stub between the through highway and the cut
 *     is removed (hwy_drop: hwy_end removes it with the manager's remover and a 3x3 retile), so nothing
 *     touches the through highway's side; the through rows go back to straight.
 *   stem whole (the through highway was cut, or a cell taken): through rows and stem -> straight, the stem cell beside
 *     the through highway -> its stock end caps (11235 / 11237 along z, 15053 / 15054 along x, state = r & 2).
 * Only cells that still hold highway. Task hwtdel: a through or stem cell with no highway on exactly one side along its
 * own highway (the player bulldozed the next cell, inside the T or right past it) gets the stock end cap facing that
 * gap instead of a straight piece, which would end the deck open. */
static int hwt_gap_cap(HwyPass *hp, int ax, int az, int r, int dx, int dz, WORD *id, int *st) {
    int stem = dz < 0, x, z, ux = stem ? 0 : 1, uz = stem ? 1 : 0, px, pz;
    if (stem) { px = dx == 0 ? 1 : -1; pz = 0; }                       /* toward the other lane of the pair */
    else { px = 0; pz = dz == 0 ? 1 : -1; }
    hwt_world(ax, az, r, dx, dz, &x, &z);
    hwy_rot(r, &ux, &uz);
    hwy_rot(r, &px, &pz);
    return hwy_gap_cap(hp, x, z, ux, uz, px, pz, id, st);              /* the shared helper (sc3netmod_hwy.c) */
}

static void hwt_break(HwyPass *hp, int ax, int az, int r, int set) {
    int k, x, z, n = 0, gap = 0, sz0 = 0, dz, j;
    for (k = 0; k < g_hwt_n; k++) {
        HwtCell *c = &g_hwt_c[k];
        if (!(c->sets & set)) continue;
        if (!c->land && c->dz < 0 && (c->dx == 0 || c->dx == 1) && c->dz < sz0) sz0 = c->dz;
    }
    for (dz = -1; dz >= sz0 && !gap; dz--)                          /* the first stem row of the T without highway */
        for (j = 0; j < 2; j++) {
            hwt_world(ax, az, r, j, dz, &x, &z);
            if (hwt_inbox(hp, x, z) && !hwy_at(hp, x, z)) gap = dz;
        }
    for (k = 0; k < g_hwt_n; k++) {
        HwtCell *c = &g_hwt_c[k];
        int hx, hz, st, stem = c->dz < 0 && (c->dx == 0 || c->dx == 1);
        WORD id;
        if (!(c->sets & set) || c->land) continue;
        hwt_world(ax, az, r, c->dx, c->dz, &x, &z);
        if (x <= hp->x0 || x >= hp->x1 || z <= hp->z0 || z >= hp->z1 || !hwy_at(hp, x, z) || hwy_claimed(x, z)) continue;
        if (stem && gap && c->dz > gap) {                           /* the stub: removed by hwy_end */
            hwy_drop(hp, x, z);
            n++;
            continue;
        }
        if (stem && !gap && c->dz == -1) {
            id = (WORD)((r & 1) ? (c->dx ? 15054 : 15053) : (c->dx ? 11237 : 11235));
            st = r & 2;
        } else if (hwt_capped(k, r, hwy_at(hp, x, z))) {                 /* task hwcap2: its highway ends here */
            hwt_cap_stock(r, c->dx, c->dz, &id, &st);
        } else if (!hwt_gap_cap(hp, ax, az, r, c->dx, c->dz, &id, &st)) { /* task hwtdel: a cut beside it */
            hwt_frame_head(c->dx, c->dz, &hx, &hz);
            hwy_rot(r, &hx, &hz);
            hwt_plain(hx, hz, &id, &st);
        }
        if (hwy_put(hp, x, z, id, st) > 0) n++;
    }
    logf("hwt: %s: T at anchor (%d,%d) turn %d is broken (%s): %d highway cells rewritten, its ramp cells revert",
         hp->who, ax, az, r, gap ? "stem cut: the stub against the through highway goes too" :
         "through highway cut or a cell taken: stem capped", n);
}

#define HWT_MINVOTE 4                 /* pieces that must agree on an anchor before it is treated as a built T */

static int hwt_any_claimed(HwyPass *hp, int ax, int az, int r, int set) {
    int k, x, z;
    for (k = 0; k < g_hwt_n; k++) {
        if (!(g_hwt_c[k].sets & set)) continue;
        hwt_world(ax, az, r, g_hwt_c[k].dx, g_hwt_c[k].dz, &x, &z);
        if (hwt_inbox(hp, x, z) && hwy_claimed(x, z)) return 1;
    }
    return 0;
}

static void hwt_run(HwyPass *hp) {
    static int cand[64][5];                    /* ax, az, r, votes, sets seen */
    int ncand = 0, x, z, r, k, j;
    const char *why;
    if (!g_hwt_n || env_off("SC3NETMOD_HWT")) return;
    /* 1. Ts already built. Every piece votes for the anchor its id (frame cell) and state (turn) imply; a stock retile
     * can leave a rewritten highway cell with another state, so only anchors with HWT_MINVOTE agreeing pieces count
     * (land pieces are Protected: a real T keeps most of its votes even when broken). Most votes first. */
    for (z = hp->z0 + 1; z < hp->z1; z++)
        for (x = hp->x0 + 1; x < hp->x1; x++) {
            DWORD v = hwy_at(hp, x, z);
            int ax, az, dx, dz;
            k = v ? hwt_cell_of(hwy_id(v)) : -1;
            if (k < 0 || hwy_claimed(x, z)) continue;
            r = hwy_st(v);
            dx = g_hwt_c[k].dx; dz = g_hwt_c[k].dz;
            hwy_rot(r, &dx, &dz);
            ax = x - dx; az = z - dz;
            for (j = 0; j < ncand; j++) if (cand[j][0] == ax && cand[j][1] == az && cand[j][2] == r) break;
            if (j == ncand) {
                if (ncand >= 64) continue;
                cand[j][0] = ax; cand[j][1] = az; cand[j][2] = r; cand[j][3] = 0; cand[j][4] = 0;
                ncand++;
            }
            cand[j][3]++;
            cand[j][4] |= g_hwt_c[k].sets | (g_hwt_c[k].sets == 1 ? 4 : 0);   /* task hwtdel: 4 = a full-T-only piece */
        }
    for (j = 0; j < ncand; j++)                       /* task hwtdel: a T partly outside the box votes with all its cells */
        if (cand[j][3] < HWT_MINVOTE) cand[j][3] = hwt_votes(hp, cand[j][0], cand[j][1], cand[j][2], &cand[j][4]);
    for (;;) {
        int best = -1, ax, az;
        for (j = 0; j < ncand; j++) if (cand[j][3] >= HWT_MINVOTE && (best < 0 || cand[j][3] > cand[best][3])) best = j;
        if (best < 0) break;
        ax = cand[best][0]; az = cand[best][1]; r = cand[best][2];
        cand[best][3] = 0;
        if (hwt_any_claimed(hp, ax, az, r, 1) && hwt_any_claimed(hp, ax, az, r, 2)) continue;   /* another T's */
        if (hwt_existing(hp, ax, az, r, 1)) continue;
        /* task hwtdel: a full T that fails is broken, never re-read as a right-in / right-out T (its cells are a subset:
         * a bulldozed through cell outside that subset turned a full T into a RIO one, far ramps removed) */
        if (!(cand[best][4] & 4) && hwt_existing(hp, ax, az, r, 2)) continue;
        InterlockedIncrement(&g_hwt_n_broken);
        hwt_break(hp, ax, az, r, (cand[best][4] & 1) ? 1 : 2);
    }
    /* 2. new Ts: the stem's end caps (gesture 1) or a stub X (gesture 2) */
    hwask_prune(hp);                                                 /* task hwask: forget declines whose T is gone */
    for (z = hp->z0 + 1; z < hp->z1; z++)
        for (x = hp->x0 + 1; x < hp->x1; x++) {
            DWORD v = hwy_at(hp, x, z);
            int gesture, ax, az;
            if (hwt_is_id(v, 11235, 15053)) gesture = 1;
            else if (hwt_is_id(v, 15113, 15114)) gesture = 2;
            else continue;
            if (hwy_claimed(x, z)) continue;
            for (r = 0; r < 4; r++) {
                int dx = 0, dz = gesture == 1 ? -1 : 0;
                hwy_rot(r, &dx, &dz);
                ax = x - dx; az = z - dz;
                if (hwt_check(hp, ax, az, r, gesture, 1, &why)) {
                    int nl = 0;                                      /* task hwask: the player decides; no = stock */
                    for (k = 0; k < g_hwt_n; k++) nl += g_hwt_c[k].land && (g_hwt_c[k].sets & 1);
                    if (hwask_ok(hp, HWASK_T, x, z, r, hwy_id(v), nl)) hwt_build(hp, ax, az, r, gesture, 1);
                    break;
                }
                if (HWT_RIO && gesture == 1 && (!strcmp(why, "far side not free") || !strcmp(why, "far side touches other highway"))) {
                    const char *why2;
                    if (hwt_check(hp, ax, az, r, gesture, 2, &why2)) { hwt_build(hp, ax, az, r, gesture, 2); break; }
                    why = why2;
                }
                if (strcmp(why, "no cap") && strcmp(why, "no cap pair") && strcmp(why, "not a stock X") &&
                    strcmp(why, "stem") && strcmp(why, "through highway") && strcmp(why, "T not inside the read box"))
                    logf("hwt: %s: T at anchor (%d,%d) turn %d refused: %s", hp->who, ax, az, r, why);
            }
        }
}

static void hwt_stats(void) {
    static LONG last;
    LONG n = g_hwt_n_full + g_hwt_n_rio + g_hwt_n_kept + g_hwt_n_broken;
    if (!g_hwt_n || n == last) return;
    last = n;
    logf("stats: hwt full Ts built=%ld, right-in/right-out built=%ld, kept=%ld, broken=%ld", g_hwt_n_full,
         g_hwt_n_rio, g_hwt_n_kept, g_hwt_n_broken);
}
