/* sc3netmod_hwdd.c - the HWDD block of sc3netmod.dll (task hwdd, highway program 2026-10-18): two diagonal highways of
 * the two families (A = x - z band 11223 / 11224, B = x + z band 15052 / 15106) that cross become a cloverleaf turned
 * 45 degrees (A on a deck over B, four loops for the left turns, four outer ramps for the right turns), or, when the
 * quadrants are not free, a flyover without ramps. #included by sc3netmod.c after sc3netmod_hwy.c; runs in rb_hwy() as
 * `hwdd_run(hp);` on hwcore's helpers (sc3netmod_hwy.c header).
 *
 * Geometry, tables, offline twin: re/tools/netmod/hwdd.py (plan, cells, ctab), art: hwdd_paint.py, package
 * examples/highway_dd_cloverleaf. Notes: verify/hwdd/RESULTS_plan.md, RESULTS.md.
 *
 * Frames. O = where the two medians cross: a cell centre (parity 'c', stock leaves a 3x3 stub around one 15149) or a
 * cell corner ('h', a 4x4 stub around a 2x2 15149), measured in game. Table rows (sc3netmod_hwdd_tab.h, generated by
 * `hwdd.py ctab`) are relative to the frame origin: the cell holding O ('c') or the cell whose low x / low z corner is
 * O ('h'). A is always the x - z family, so the layout never turns: one table per parity and mode.
 *
 * Rule, per highway pass:
 *  - candidates: (1) the stock stub (every stub cell holds its stock piece) anchored on a 15149 of the read box,
 *    (2) any cell of the read box holding an HWDD piece: its (id, state) names one row of one table, so O.
 *    Cells outside the read box are read with hwy_read (an interchange is up to 16 x 16 with its check margin).
 *  - CLOVERLEAF when: every on-highway row (crossing, highway + ramp) holds highway and is unclaimed; every plain-band
 *    row holds highway (the arms go on 2 rows past the interchange; a band cell the stock tiler re-placed gets its
 *    stock piece back); every "no highway" row holds none or an HWDD piece; and the ramp rows on land either ALL hold their pieces
 *    (an existing interchange) or NONE does and all are hwy_free, unclaimed and inside the read box (a fresh build,
 *    which also needs every written row inside the box). Then every row is written / kept (hwy_put).
 *  - else FLYOVER (its own table: the crossing cells only, A's deck over B, no ramps) on the same tests.
 *  - else nothing: hwy_end reverts the HWDD pieces of the box (land ones removed, on-highway ones re-tiled).
 *  A broken cloverleaf (a ramp cell bulldozed) becomes the flyover: hwy_end reverts its cells inside the read box,
 *  hwdd_unbuild the ones outside (ramps on land: hwy_drop, which takes any map cell; on-highway cells: their stock
 *  piece back with hwy_put).
 * Saves: on-highway pieces save as their base at their state = the stock piece the cell held (bands, 73 / 15051 /
 * 15149 stub pieces); land pieces as 15099 (hwcore's land base, as hwdx).
 * Off: SC3NETMOD_HWDD=0.
 */

typedef struct { signed char dx, dz; BYTE role; WORD id; BYTE st; WORD base; BYTE bst, land; } HwddRow;
typedef struct { signed char dx, dz; WORD id; BYTE st; } HwddStub;
#include "sc3netmod_hwdd_tab.h"

#define HWDD_MAXC 32
enum { HWDD_CROSS = 1, HWDD_JOIN = 2, HWDD_LAND = 3, HWDD_BAND = 4, HWDD_NONE = 5 };

typedef struct { int ox, oz, par; } HwddCand;

static int g_hwdd_off = -1;
static volatile LONG g_hwdd_n_new, g_hwdd_n_keep, g_hwdd_n_fly, g_hwdd_n_none;

static const HwddRow *hwdd_tab(int par, int fly, int *n) {
    if (par == 0) { *n = fly ? HWDD_N_FLY_C : HWDD_N_CLOVER_C; return fly ? g_hwdd_fly_c : g_hwdd_clover_c; }
    *n = fly ? HWDD_N_FLY_H : HWDD_N_CLOVER_H;
    return fly ? g_hwdd_fly_h : g_hwdd_clover_h;
}

static DWORD hwdd_rd(HwyPass *hp, int x, int z) {
    if (x >= hp->b.x0 && z >= hp->b.z0 && x < hp->b.x0 + hp->b.w && z < hp->b.z0 + hp->b.h) return hwy_at(hp, x, z);
    return hwy_read(hp->mgr, hp->lay, x, z, hp->W, hp->H);
}

static int hwdd_inbox(HwyPass *hp, int x, int z) {                   /* hwy_end reverts one cell in from the border */
    return x > hp->x0 && z > hp->z0 && x < hp->x1 && z < hp->z1;
}

static int hwdd_mine(WORD id) { return id >= HWDD_ID0 && id <= HWDD_ID1; }

/* a highway end cap: diagonal 14999 (measured on both drag ends, 2026-10-18) / 15059, straight 15053 / 15054 / 11235 /
 * 11237 (verify/highways/STOCK.md). An arm cell holding one means the arm ends there. */
static int hwdd_cap(WORD id) {
    return id == 14999 || id == 15059 || id == 15053 || id == 15054 || id == 11235 || id == 11237;
}

/* a stock piece in a state: the band middles and 15149 look the same a half turn round (11224.0 = 11224.2) */
static int hwdd_is(DWORD v, WORD id, int st) {
    WORD i = hwy_id(v);
    int s = hwy_st(v);
    if (!v || i != id) return 0;
    if (s == st) return 1;
    return (id == 11224 || id == 15106 || id == 15149) && ((s ^ st) & 1) == 0;
}

static int hwdd_stub(HwyPass *hp, int ox, int oz, int par) {
    const HwddStub *t = par ? g_hwdd_stub_h : g_hwdd_stub_c;
    int n = par ? HWDD_N_STUB_H : HWDD_N_STUB_C, k;
    for (k = 0; k < n; k++)
        if (!hwdd_is(hwdd_rd(hp, ox + t[k].dx, oz + t[k].dz), t[k].id, t[k].st)) return 0;
    return 1;
}

static void hwdd_add(HwddCand *c, int *nc, int ox, int oz, int par) {
    int k;
    for (k = 0; k < *nc; k++) if (c[k].ox == ox && c[k].oz == oz && c[k].par == par) return;
    if (*nc >= HWDD_MAXC) return;
    c[*nc].ox = ox; c[*nc].oz = oz; c[*nc].par = par; (*nc)++;
}

/* why the last hwdd_test said no (logged by the caller) */
static char g_hwdd_why[96];

#define HWDD_NO(fmt, a, b, c) do { _snprintf(g_hwdd_why, sizeof(g_hwdd_why), fmt, a, b, c); return 0; } while (0)

/* -> 2 build (fresh), 1 keep (existing), 0 no. On-highway and plain-band rows take ANY highway occupant: a stock
 * retile that reaches the interchange (an edit on an arm within the tiler's flood radius) re-places them, and next to
 * the ramp pieces (Protected base 15099) the tiler picks pieces other than the plain band; the block writes them back. */
static int hwdd_test(HwyPass *hp, int ox, int oz, int par, int fly) {
    int n, k, nland = 0, have = 0, freec = 0, allin = 1;
    const HwddRow *t = hwdd_tab(par, fly, &n);
    g_hwdd_why[0] = 0;
    for (k = 0; k < n; k++) {
        const HwddRow *r = &t[k];
        int x = ox + r->dx, z = oz + r->dz;
        DWORD v = hwdd_rd(hp, x, z);
        int mine = v && hwy_id(v) == r->id && hwy_st(v) == r->st;
        switch (r->role) {
        case HWDD_CROSS: case HWDD_JOIN:
            if (!v) HWDD_NO("(%d,%d) on the highway holds no highway%s", x, z, "");
            if (hwy_claimed(x, z)) HWDD_NO("(%d,%d) claimed by another block%s", x, z, "");
            if (!hwdd_inbox(hp, x, z)) allin = 0;
            if (mine) have++;
            break;
        case HWDD_LAND:
            nland++;
            if (hwy_claimed(x, z)) HWDD_NO("ramp cell (%d,%d) claimed by another block%s", x, z, "");
            if (mine) { have++; break; }
            if (v) HWDD_NO("ramp cell (%d,%d) holds highway piece %u", x, z, hwy_id(v));
            if (!hwdd_inbox(hp, x, z)) { allin = 0; break; }
            if (hwy_free(hp, x, z)) freec++;
            break;
        case HWDD_BAND:
            if (!v) HWDD_NO("arm cell (%d,%d) holds no highway (the arm ends)%s", x, z, "");
            if (hwdd_cap(hwy_id(v))) HWDD_NO("arm cell (%d,%d) holds end cap %u (the arm ends)", x, z, hwy_id(v));
            break;
        default:                                                         /* HWDD_NONE */
            if (v && !hwdd_mine(hwy_id(v))) HWDD_NO("(%d,%d) holds highway piece %u (another highway)", x, z, hwy_id(v));
            break;
        }
    }
    if (nland) {                                                         /* cloverleaf: all ramps or none + all free */
        int hl = 0;
        for (k = 0; k < n; k++)
            if (t[k].role == HWDD_LAND) {
                DWORD v = hwdd_rd(hp, ox + t[k].dx, oz + t[k].dz);
                if (v && hwy_id(v) == t[k].id && hwy_st(v) == t[k].st) hl++;
            }
        if (hl == nland) return 1;
        if (hl) HWDD_NO("%d of %d ramp cells hold their piece (a ramp was removed)%s", hl, nland, "");
        if (freec != nland) HWDD_NO("%d of %d ramp cells free%s", freec, nland, "");
        if (!allin) HWDD_NO("a fresh build reaches past the pass box%s%s%s", "", "", "");
        return 2;
    }
    if (have) return 1;                                                  /* flyover: existing, or fresh in the box */
    if (!allin) HWDD_NO("a fresh flyover reaches past the pass box%s%s%s", "", "", "");
    return 2;
}

static void hwdd_write(HwyPass *hp, int ox, int oz, int par, int fly) {
    int n, k, bad = 0;
    const HwddRow *t = hwdd_tab(par, fly, &n);
    for (k = 0; k < n; k++) {
        const HwddRow *r = &t[k];
        int x = ox + r->dx, z = oz + r->dz;
        if (r->role == HWDD_BAND) {                                      /* a plain arm cell the tiler re-placed */
            DWORD v = hwdd_rd(hp, x, z);
            if (v && !hwdd_is(v, r->base, r->bst) && !hwdd_mine(hwy_id(v)) && hwdd_inbox(hp, x, z))
                hwy_put(hp, x, z, r->base, r->bst);
            continue;
        }
        if (r->role > HWDD_LAND) continue;
        if (hwy_put(hp, x, z, r->id, r->st) < 0) bad++;
    }
    if (bad) logf("### hwdd: %s: %d cells refused at O frame (%d,%d) %c%s", hp->who, bad, ox, oz, par ? 'h' : 'c',
                  fly ? " flyover" : "");
}

/* a cloverleaf that no longer holds: its cells OUTSIDE the read box (hwy_end reverts the inside) go back too. Ramp
 * pieces on land are dropped (hwy_drop: queued, removed in hwy_end); cells on the player's highway get their stock
 * piece back (hwy_put of the base), so the highway itself stays. Only cells holding this interchange's own piece. */
static void hwdd_unbuild(HwyPass *hp, int ox, int oz, int par) {
    int n, k, nd = 0;
    const HwddRow *t = hwdd_tab(par, 0, &n);
    for (k = 0; k < n; k++) {
        const HwddRow *r = &t[k];
        int x = ox + r->dx, z = oz + r->dz;
        DWORD v;
        if (r->role > HWDD_LAND || hwdd_inbox(hp, x, z)) continue;
        v = hwdd_rd(hp, x, z);
        if (!v || hwy_id(v) != r->id || hwy_st(v) != r->st) continue;
        if (r->role == HWDD_LAND) hwy_drop(hp, x, z);
        else hwy_put(hp, x, z, r->base, r->bst);
        nd++;
    }
    if (nd) logf("hwdd: %s: cloverleaf at frame (%d,%d) %c broken: %d cells outside the pass box reverted", hp->who, ox,
                 oz, par ? 'h' : 'c', nd);
}

static void hwdd_run(HwyPass *hp) {
    HwddCand c[HWDD_MAXC];
    int nc = 0, x, z, k, j;
    if (!hp) return;
    if (g_hwdd_off < 0) {
        g_hwdd_off = env_off("SC3NETMOD_HWDD") || hwy_piece(HWDD_ID0) < 0;
        logf("hwdd: %s (pieces %d..%d)", g_hwdd_off ? "off (SC3NETMOD_HWDD=0 or package not installed)" : "on",
             HWDD_ID0, HWDD_ID1);
    }
    if (g_hwdd_off) return;
    for (z = hp->z0; z <= hp->z1; z++)
        for (x = hp->x0; x <= hp->x1; x++) {
            DWORD v = hwy_at(hp, x, z);
            WORD id = hwy_id(v);
            if (!v) continue;
            if (id == 15149) {                                           /* the stock stub around O */
                if (hwdd_stub(hp, x, z, 0)) hwdd_add(c, &nc, x, z, 0);
                for (j = 0; j < 4; j++) {                                /* 'h': the 15149 is one of the 2x2 */
                    int ox = x + 1 - (j & 1), oz = z + 1 - (j >> 1);
                    if (hwdd_stub(hp, ox, oz, 1)) hwdd_add(c, &nc, ox, oz, 1);
                }
            } else if (hwdd_mine(id)) {                                  /* an existing interchange: O from the row */
                int par, fly, n, st = hwy_st(v);
                for (par = 0; par < 2; par++)
                    for (fly = 0; fly < 2; fly++) {
                        const HwddRow *t = hwdd_tab(par, fly, &n);
                        for (k = 0; k < n; k++)
                            if (t[k].id == id && t[k].st == st) hwdd_add(c, &nc, x - t[k].dx, z - t[k].dz, par);
                    }
            }
        }
    for (k = 0; k < nc; k++) {
        int r = hwdd_test(hp, c[k].ox, c[k].oz, c[k].par, 0), fly = 0;
        if (!r) {
            logf("hwdd: %s: frame (%d,%d) %c: no cloverleaf: %s", hp->who, c[k].ox, c[k].oz, c[k].par ? 'h' : 'c',
                 g_hwdd_why);
            hwdd_unbuild(hp, c[k].ox, c[k].oz, c[k].par);
            r = hwdd_test(hp, c[k].ox, c[k].oz, c[k].par, 1); fly = 1;
        }
        if (!r) {
            InterlockedIncrement(&g_hwdd_n_none);
            logf("hwdd: %s: frame (%d,%d) %c: no flyover either (%s), left to stock", hp->who, c[k].ox, c[k].oz,
                 c[k].par ? 'h' : 'c', g_hwdd_why);
            continue;
        }
        hwdd_write(hp, c[k].ox, c[k].oz, c[k].par, fly);
        InterlockedIncrement(r == 2 ? &g_hwdd_n_new : &g_hwdd_n_keep);
        if (fly) InterlockedIncrement(&g_hwdd_n_fly);
        if (r == 2 || !strcmp(hp->who, "load"))
            logf("hwdd: %s: %s %s at frame (%d,%d) %c", hp->who, r == 2 ? "built" : "kept",
                 fly ? "flyover" : "cloverleaf", c[k].ox, c[k].oz, c[k].par ? 'h' : 'c');
    }
}

static void hwdd_stats(void) {
    static LONG last;
    LONG n = g_hwdd_n_new + g_hwdd_n_keep + g_hwdd_n_none;
    if (g_hwdd_off != 0 || n == last) return;
    last = n;
    logf("stats: hwdd built=%ld, kept=%ld (flyovers %ld), refused=%ld", g_hwdd_n_new, g_hwdd_n_keep, g_hwdd_n_fly,
         g_hwdd_n_none);
}
