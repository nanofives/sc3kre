#!/usr/bin/env python3
r"""hwt_twin.py - offline twin of the HWT block (re/harness/src/sc3netmod_hwt.c, stream hwt 2026-10-18).

  py -3.12 hwt_twin.py selftest              the rule on the stock grids measured in game (verify/hwt/README.md 1)
  py -3.12 hwt_twin.py match CITY.sc3        every T the block would build / keep / find broken in a save

Same cells (hwt_cells.py, generated by hwt_build.py table), same rule and the same order as the C block:
  1. built Ts by vote (each of our pieces names an anchor; >= HWT_MINVOTE agreeing = a T), most votes first: kept when
     every cell inside the box holds its piece, or some highway (a rewritten highway cell) or is free (a land cell);
     else broken.
  2. new Ts from the stem's end caps (gesture 1) or a stock stub X (gesture 2), every rotation: the full set only.
     The right-in / right-out set for a blocked far side is off (owner call 2026-10-18; RIO = True turns it back on).
Free cell = no surface occupant, no building, flat (when a height map is given); the DLL's hwy_free also runs the stock
On-ramp free test (trees ok), which this twin does not model. The read box is not modelled (the whole grid is the box).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import hwt_cells  # noqa: E402
from hwt_layout import (Grid, heading, rot, world, stock_cap_from_minus_z, stock_stub_x, synth_cap,  # noqa: E402
                        PIECE_OF)

CELLS = hwt_cells.CELLS
BY_ID = {c["id"]: c for c in CELLS}
MINVOTE = 4
RIO = False      # owner 2026-10-18: far side built up -> leave the T stock (C: HWT_RIO 0)
CAPS0, CAPS1 = (11235, 15053), (11237, 15054)
X_CENTRE, X_ARM_Z, X_ARM_X = (15113, 15114), (15150, 15153), (15107, 15108)


def frame_head(dx, dz):
    if dz == 0:
        return (1, 0)
    if dz == 1:
        return (-1, 0)
    return (0, -1) if dx == 0 else (0, 1)


def straight(g, a, r, dx, dz):
    return heading(g.get(world(a, r, (dx, dz)))) == rot(*frame_head(dx, dz), r)


def in_set(dx, dz, s):
    return any(c["sets"] & s and c["dx"] == dx and c["dz"] == dz for c in CELLS)


def check(g, a, r, gesture, s, claimed):
    sel = [c for c in CELLS if c["sets"] & s]
    tx = [c["dx"] for c in sel if c["dz"] in (0, 1)]
    sz0 = min([c["dz"] for c in sel if c["dz"] < 0 and c["dx"] in (0, 1)] + [0])
    for dz in range(-2, sz0 - 2, -1):
        if not (straight(g, a, r, 0, dz) and straight(g, a, r, 1, dz)):
            return "stem"
    if gesture == 1:
        p0, p1 = g.get(world(a, r, (0, -1))), g.get(world(a, r, (1, -1)))
        if not p0 or p0[0] not in CAPS0:
            return "no cap"
        if not p1 or p1[0] not in CAPS1:
            return "no cap pair"
    else:
        pat = [((0, 0), X_CENTRE), ((1, 0), X_CENTRE), ((0, 1), X_CENTRE), ((1, 1), X_CENTRE),
               ((0, -1), X_ARM_Z), ((1, -1), X_ARM_Z), ((0, 2), X_ARM_Z), ((1, 2), X_ARM_Z),
               ((-1, 0), X_ARM_X), ((-1, 1), X_ARM_X), ((2, 0), X_ARM_X), ((2, 1), X_ARM_X)]
        for cell, ids in pat:
            p = g.get(world(a, r, cell))
            if not p or p[0] not in ids:
                return "not a stock X"
        if any(g.get(world(a, r, (k, 3))) for k in (0, 1)):
            return "far arm continues: a full X (hwx)"
    for dx in range(min(tx) - 1, max(tx) + 2):
        if gesture == 2 and -1 <= dx <= 2:
            continue
        if not (straight(g, a, r, dx, 0) and straight(g, a, r, dx, 1)):
            return "through highway"
    for c in sel:
        w = world(a, r, (c["dx"], c["dz"]))
        if w in claimed:
            return "cell claimed by another block"
        if c["kind"] != "new":
            continue
        if gesture == 2 and c["dz"] == 2 and c["dx"] in (0, 1):
            continue
        if not g.free(w):
            return "far side not free" if c["dz"] >= 2 else "stem side not free"
        for d in ((-1, 0), (0, -1), (1, 0), (0, 1)):
            n = (c["dx"] + d[0], c["dz"] + d[1])
            if in_set(n[0], n[1], s) or n[1] in (0, 1) or (n[1] < 0 and n[0] in (0, 1)):
                continue
            if gesture == 2 and n[1] == 2 and n[0] in (0, 1):
                continue
            if g.get(world(a, r, n)):
                return "far side touches other highway" if c["dz"] >= 2 else "stem side touches other highway"
    return None


def existing(g, a, r, s, claimed):
    mine = 0
    for c in CELLS:
        if not c["sets"] & s:
            continue
        w = world(a, r, (c["dx"], c["dz"]))
        if w in claimed:
            return False
        v = g.get(w)
        if v and v[0] == c["id"] and v[1] == r:
            mine += 1
            continue
        if c["kind"] != "new" and v:
            continue
        if v and v[0] in BY_ID:
            return False
        if c["kind"] == "new" and not v and g.free(w):
            continue
        return False
    return mine > 0


def place(a, r, s):
    return {world(a, r, (c["dx"], c["dz"])): (c["id"], r) for c in CELLS if c["sets"] & s}


def run(g):
    """-> [(what, gesture, anchor, r, set)], and g updated in place with the pieces written"""
    out, claimed = [], set()
    votes = {}
    for xz, p in g.c.items():
        c = BY_ID.get(p[0])
        if not c:
            continue
        r = p[1]
        d = rot(c["dx"], c["dz"], r)
        key = (xz[0] - d[0], xz[1] - d[1], r)
        v = votes.setdefault(key, [0, 0])
        v[0] += 1
        v[1] |= c["sets"]
    for (ax, az, r), (n, sets) in sorted(votes.items(), key=lambda kv: -kv[1][0]):
        if n < MINVOTE:
            continue
        for s in (1, 2):
            if existing(g, (ax, az), r, s, claimed):
                cells = place((ax, az), r, s)
                g.c.update(cells)
                claimed |= set(cells)
                out.append(("kept", 0, (ax, az), r, s))
                break
        else:
            out.append(("broken", 0, (ax, az), r, 1 if sets & 1 else 2))
    for xz, p in sorted(g.c.items()):
        if p[0] in CAPS0:
            gesture = 1
        elif p[0] in X_CENTRE:
            gesture = 2
        else:
            continue
        if xz in claimed:
            continue
        for r in range(4):
            d = rot(0, -1 if gesture == 1 else 0, r)
            a = (xz[0] - d[0], xz[1] - d[1])
            why = check(g, a, r, gesture, 1, claimed)
            s = 1
            if RIO and why in ("far side not free", "far side touches other highway") and gesture == 1:
                why, s = check(g, a, r, gesture, 2, claimed), 2
            if why is None:
                cells = place(a, r, s)
                if gesture == 2:
                    for cell in ((-1, 0), (-1, 1), (2, 0), (2, 1)):
                        if not in_set(cell[0], cell[1], s):
                            cells[world(a, r, cell)] = PIECE_OF[rot(*frame_head(*cell), r)]
                g.c.update(cells)
                claimed |= set(cells)
                out.append(("built", gesture, a, r, s))
                break
    return out


def selftest():
    ok = True

    def t(cond, msg):
        nonlocal ok
        print(("ok   " if cond else "FAIL ") + msg)
        ok &= bool(cond)

    full = [c for c in CELLS if c["sets"] & 1]
    rio = [c for c in CELLS if c["sets"] & 2]
    t(len(full) == 50 and sum(c["kind"] == "new" for c in full) == 30, "full set: 50 cells, 30 new (the build of 2026-10-18)")
    t(len(rio) == 18, "rio set: 18 cells")
    t(len({c["id"] for c in CELLS}) == len(CELLS) and max(c["id"] for c in CELLS) <= 21259, "ids unique, in range")
    # the measured stock grid (README section 1): the through highway ends 4 cells from the stem, the T needs straight
    # through highway 3 cells one way (frame dx -3) and 8 the other
    t(run(Grid(stock_cap_from_minus_z())) == [("built", 1, (49, 27), 0, 1)], "measured cap grid (gesture 1, from -z)")
    # the in-game runs: long through highways (lab drags x 44..72, z 4..44, x 96..114), anchors as the DLL logged
    for r in range(4):
        g = Grid(synth_cap((60, 60), r))
        r1 = run(g)
        t(r1 == [("built", 1, (60, 60), r, 1)], "gesture 1, turn %d: %s" % (r, r1))
        r2 = run(g)
        t(r2 == [("kept", 0, (60, 60), r, 1)], "next pass keeps it (turn %d)" % r)
    c = stock_stub_x()                                   # the stub X with the through highway x 88..120
    for x in range(88, 121):
        if not 99 <= x <= 102:
            c[(x, 87)], c[(x, 88)] = (15051, 2), (15051, 0)
    for z in range(90, 99):
        c[(100, z)], c[(101, z)] = (73, 2), (73, 0)
    g = Grid(c)
    res = run(g)
    t(res == [("built", 2, (101, 88), 2, 1)], "gesture 2 stub X: %s" % res)
    t(g.get((102, 87)) == (15051, 2), "the stub X's unused arm cell goes back to plain 15051")
    c2 = dict(c)
    for z in range(83, 86):
        c2[(100, z)], c2[(101, z)] = (73, 2), (73, 0)
    t(run(Grid(c2)) == [], "full X refused (hwx)")
    g = Grid(synth_cap((60, 60), 0), buildings=[(61, 64, 1, 1)])           # frame (1, 4): the loop ring
    t(run(g) == [], "far side blocked by a building -> left stock (owner call)")
    g = Grid(synth_cap((60, 60), 0), buildings=[(62, 63, 1, 1)])           # frame (2, 3): the loop's eye
    t(run(g) == [("built", 1, (60, 60), 0, 1)], "a building in the loop's eye does not block the full T")
    g = Grid(synth_cap((60, 60), 0), buildings=[(58, 59, 1, 1)])           # frame (-2, -1): stem-side ramp
    t(run(g) == [], "stem side blocked -> refused")
    g = Grid(synth_cap((60, 60), 0))
    run(g)
    del g.c[(60, 57)]                                                       # frame (0, -3): a stem cell
    t(run(g) == [("broken", 0, (60, 60), 0, 1)], "a stem cell cut -> broken")
    print("selftest", "PASSED" if ok else "FAILED")
    return 0 if ok else 1


def match_save(path):
    sys.path.insert(0, os.path.dirname(HERE))
    from netmod import tiler
    city = tiler.City.load(path)
    cells = {xy: (p.id, p.state) for xy, p in city.layers["surface"].items()}
    bl = [(a, b, sa, sb) for recs in getattr(city, "buildings", {}).values() for (a, b, sa, sb, key) in recs]
    g = Grid(cells, bl)
    for row in run(g):
        print(row)


def main(argv):
    if len(argv) > 1 and argv[1] == "selftest":
        return selftest()
    if len(argv) > 2 and argv[1] == "match":
        match_save(argv[2])
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
