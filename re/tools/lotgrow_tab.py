"""Generate re/harness/src/sc3simrun_lotgrow_tab.h: the byte check of the 9 SIMRCI zone-developer rule bodies that
sc3simrun LOTGROW replaces (re/analysis/LOT_SHAPES.md section 11, round 2026-11-24d).

For each body: its VA, length, the rule-interface vtable slot that points at it, the relocated dwords inside it
(offsets), and an FNV-1a hash of the body with those dwords zeroed. At arm time sc3simrun hashes the mapped body the
same way, so any other patch inside a body (or a different SIMRCI build) leaves LOTGROW off.

    py -3.12 re/tools/lotgrow_tab.py [path\\to\\SIMRCI.DLL]   (default original/modules/SIMRCI.DLL)
"""
import os, sys, struct
import pefile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
# MAIN holds original/ (gitignored, so a worktree has none): walk up to the first folder that has it
def find_dll():
    d = ROOT
    for _ in range(6):
        p = os.path.join(d, 'original', 'modules', 'SIMRCI.DLL')
        if os.path.exists(p): return p
        d = os.path.dirname(d)
    raise SystemExit('SIMRCI.DLL not found; pass its path')

# kind 0 = block fill, 1 = corners + strip + fill, 2 = com block. flag: kind 0 = the per-cell vt+0x6c transport test,
# kind 1 = skip the corner step when the corner list is empty (0x10027699 `jbe` at 0x1002790c; 0x1000dd1a has no guard).
# tunables in the order: demand %, min W, min D, max W, max D, pick %
RULES = [
    # name,              body,       len,  vtable,     kind, transport, dem,        minw,       mind,       maxw,       maxd,       pick
    ('res_block_v3',     0x10026b01, 763,  0x1004ccb0, 0, 0, 0x10057ff4, 0x10057fe4, 0x10057fe8, 0x10057fec, 0x10057ff0, 0x10057ff8),
    ('res_block_v2',     0x10020762, 785,  0x1004c8dc, 0, 1, 0x10057c04, 0x10057bf4, 0x10057bf8, 0x10057bfc, 0x10057c00, 0x10057c08),
    ('ind_block_v2',     0x10014794, 785,  0x1004c3e8, 0, 1, 0x10057654, 0x10057644, 0x10057648, 0x1005764c, 0x10057650, 0x10057658),
    ('ind_block_v3',     0x100152a2, 785,  0x1004c428, 0, 1, 0x1005766c, 0x1005765c, 0x10057660, 0x10057664, 0x10057668, 0x10057670),
    ('ind_block_v1',     0x10013c66, 785,  0x1004c3a8, 0, 1, 0x1005763c, 0x1005762c, 0x10057630, 0x10057634, 0x10057638, 0x10057640),
    ('com_block_v1',     0x1000c3eb, 785,  0x1004c10c, 0, 1, 0x100574bc, 0x100574ac, 0x100574b0, 0x100574b4, 0x100574b8, 0x100574c0),
    ('res_corner',       0x10027699, 1862, 0x1004ccf0, 1, 1, 0x1005800c, 0x10057ffc, 0x10058000, 0x10058004, 0x10058008, 0x10058010),
    ('com_corner',       0x1000dd1a, 1847, 0x1004c18c, 1, 0, 0x100574f0, 0x100574e0, 0x100574e4, 0x100574e8, 0x100574ec, 0x100574f4),
    ('com_block',        0x1000cf87, 1266, 0x1004c14c, 2, 0, 0x100574d8, 0x100574c8, 0x100574cc, 0x100574d0, 0x100574d4, 0x100574dc),
]
SLOT = 0x1c
RAND = 0x10039a9a

def fnv(b):
    h = 0x811c9dc5
    for c in b:
        h = ((h ^ c) * 0x01000193) & 0xffffffff
    return h

def main():
    path = sys.argv[1] if len(sys.argv) > 1 else find_dll()
    pe = pefile.PE(path)
    base = pe.OPTIONAL_HEADER.ImageBase
    assert base == 0x10000000, hex(base)
    relocs = set()
    for blk in pe.DIRECTORY_ENTRY_BASERELOC:
        for e in blk.entries:
            if e.type == 3: relocs.add(e.rva + base)
    out = ['/* generated by re/tools/lotgrow_tab.py from SIMRCI.DLL 2.0.949 (TimeDateStamp 0x%08x, SizeOfImage 0x%x) */'
           % (pe.FILE_HEADER.TimeDateStamp, pe.OPTIONAL_HEADER.SizeOfImage),
           '#define LG_RCI_STAMP 0x%08xu' % pe.FILE_HEADER.TimeDateStamp,
           '#define LG_RCI_SIZE  0x%xu' % pe.OPTIONAL_HEADER.SizeOfImage,
           '#define LG_RAND      0x%08xu   /* cRZRandom::RandomUint32Uniform */' % RAND,
           '#define LG_MAXREL 24',
           'static const LG_RULE g_lg_rules[LG_NRULES] = {']
    for (name, body, n, vt, kind, tr, *tune) in RULES:
        slot = vt + SLOT
        ptr = struct.unpack('<I', pe.get_data(slot - base, 4))[0]
        assert ptr == body, (name, hex(ptr))
        data = bytearray(pe.get_data(body - base, n))
        rel = sorted(r - body for r in relocs if body <= r < body + n)
        assert len(rel) <= 24, (name, len(rel))
        # every tunable must be referenced by a relocated dword in the body
        refs = {struct.unpack_from('<I', data, o)[0] for o in rel}
        for t in tune: assert t in refs, (name, hex(t))
        for o in rel: data[o:o + 4] = b'\0\0\0\0'
        h = fnv(data)
        out.append('    { "%s", 0x%08xu, %d, 0x%08xu, %d, %d, { %s }, %d, { %s }, 0x%08xu },'
                   % (name, body, n, slot, kind, tr, ', '.join('0x%08xu' % t for t in tune), len(rel),
                      ', '.join(str(o) for o in rel), h))
    out.append('};')
    dst = os.path.join(ROOT, 're', 'harness', 'src', 'sc3simrun_lotgrow_tab.h')
    with open(dst, 'w', newline='\n') as f: f.write('\n'.join(out) + '\n')
    print('wrote', dst)

if __name__ == '__main__':
    main()
